def discover_csv(preferred, expected_names, patient=None):
    preferred = Path(preferred)
    if preferred.is_file():
        if has_other_representation(preferred):
            raise ValueError(f'An A1 CSV is required: {preferred}')
        return preferred
    wanted = {norm(name) for name in expected_names}
    candidates = []
    for directory, dirs, files in os.walk(DATA_ROOT):
        dirs[:] = [d for d in dirs if not d.startswith('.') and not has_other_representation(Path(directory) / d)]
        for name in files:
            p = Path(directory) / name
            if p.suffix.lower() != '.csv' or norm(name) not in wanted or has_other_representation(p):
                continue
            hints = patient_hints(p)
            if patient is not None and hints and hints != {patient}:
                continue
            candidates.append(p)
    candidates = sorted(set(candidates))
    if len(candidates) == 1:
        print(f'Resolved CSV: {candidates[0]}')
        return candidates[0]
    if candidates and len({file_sha256(p) for p in candidates}) == 1:
        print(f'Identical CSV copies found; using {candidates[0]}')
        return candidates[0]
    raise FileNotFoundError(f'Expected a unique CSV for {preferred.name}. Found {len(candidates)} candidates: '
                            f'{[str(p) for p in candidates]}. Edit the corresponding path in Settings.')


def explicit_a1_image(path):
    path = Path(path)
    folder_evidence = any(re.search(r'(?<![a-z0-9])a1(?=$|[^a-z0-9]|train|test|topomap|image)',
                                   part, re.I) for part in path.parent.parts)
    other_filename = re.search(r'(?<![a-z0-9])a[2-5](?:d[1-5])*(?=$|[^a-z0-9])', path.stem, re.I)
    return folder_evidence and not other_filename and not has_other_representation(path)


class A1ImageResolver(ImageResolver):
    def __init__(self, roots):
        super().__init__(roots, 'A1 images')
        self.files = {p for p in self.files if explicit_a1_image(p)}
        for index in (self.by_name, self.by_pg, self.by_pew):
            for key in list(index):
                index[key] = [p for p in index[key] if p in self.files]
        print(f'Positive A1-folder verification: {len(self.files)} eligible images.')
        self.copy_hashes = {}

    def choose(self, candidates, pid, label, method):
        valid = []
        for path in sorted(set(candidates)):
            hints = patient_hints(path)
            if pid and hints and hints != {pid}:
                continue
            actual_label = folder_label(path)
            if actual_label is not None and actual_label != label:
                continue
            valid.append(path)
        if len(valid) == 1:
            return str(valid[0]), method
        if len(valid) > 1:
            # Multiple Drive copies are acceptable only after verifying the same decoded RGB image.
            hashes = set()
            for path in valid:
                key = str(path)
                if key not in self.copy_hashes:
                    with Image.open(path) as image:
                        rgb = image.convert('RGB')
                        payload = str(rgb.size).encode() + rgb.tobytes()
                    self.copy_hashes[key] = hashlib.sha256(payload).hexdigest()
                hashes.add(self.copy_hashes[key])
            if len(hashes) == 1:
                return str(valid[0]), method + ': verified identical image copies'
            raise ValueError(f'Ambiguous {method}: different images match {[str(p) for p in valid[:8]]}')
        return None

    def resolve(self, raw, filename, pid, label, csv_parent=None):
        raw = clean_path(raw)
        if raw and not Path(raw).is_absolute() and csv_parent is not None:
            candidate = (Path(csv_parent) / raw).resolve()
            if candidate in self.files:
                chosen = self.choose([candidate], pid, label, 'path relative to CSV')
                if chosen:
                    return chosen
        return super().resolve(raw, filename, pid, label)


def row_identity(row, columns, paths, forced_patient=None):
    patient_col = pick_column(columns, ['patient_id', 'patient', 'subject_id', 'subject'], required=False)
    hints = set()
    if patient_col and pd.notna(row[patient_col]):
        value = str(row[patient_col]).strip()
        hints.update(patient_hints(value))
        numeric = integer_identifier(value)
        if numeric is not None:
            hints.add(f'{int(numeric):02d}')
    identity_text = original_identity_text(row, columns, paths)
    for value in identity_text:
        hints.update(metadata_patient_hints(value))
    if forced_patient is not None:
        hints.add(forced_patient)
    if len(hints) != 1:
        prefixes = sorted({p for value in identity_text if (p := window_filename_prefix(value))})
        raise ValueError(f'Cannot establish one patient identity; found {sorted(hints)}; filename prefixes={prefixes}. '
                         'Supply original patient metadata or set PATIENT_FILENAME_PREFIXES in Settings '
                         'only after confirming the patient. A remaining patient is never guessed by elimination.')
    pid = next(iter(hints))
    serials, edfs, windows = set(), set(), set()
    for serial_col in columns.columns:
        if norm(serial_col) in {'globalserialid', 'globalserial', 'globalserialnumber'} and pd.notna(row[serial_col]):
            serial = global_serial_identifier(row[serial_col])
            if serial is None:
                raise ValueError(f'Invalid original global serial in {serial_col}: {row[serial_col]!r}')
            serials.add(serial)
    for value in identity_text:
        _, g, w, edf = signature(value)
        if g is not None:
            serials.add(str(g))
        if edf is not None:
            edfs.add(edf)
            if w is not None:
                windows.add(str(w))
    if len(serials) > 1 or len(edfs) > 1 or len(windows) > 1:
        raise ValueError(f'Conflicting window identifiers: G={serials}, EDF={edfs}, W={windows}')
    serial = next(iter(serials), '')
    edf = next(iter(edfs), '')
    window = next(iter(windows), '')
    if REQUIRE_ORIGINAL_WINDOW_IDS and not serial and not (edf and window):
        raise ValueError('Original window identity is missing. Preserve Global_Serial or original EDF/window metadata '
                         'in blinded CSVs; a blinded image counter is not an original window ID.')
    return pid, serial, edf, window


def load_a1_metadata(csv_path, dataset, resolver, forced_patient=None):
    frame = pd.read_csv(csv_path)
    frame.columns = [str(c).strip().lstrip('\ufeff') for c in frame.columns]
    if frame.empty or frame.columns.duplicated().any() or pd.Index([norm(c) for c in frame.columns]).duplicated().any():
        raise ValueError(f'{dataset}: empty CSV or duplicate/ambiguous column names')
    override = COLUMN_OVERRIDES.get(dataset, {})
    path_col = pick_column(frame, ['blinded_image_path', 'image_path', 'blinded_path', 'topomap_path',
                                  'file_path', 'filepath', 'path'], override.get('path'), False)
    name_col = pick_column(frame, ['blinded_filename', 'blinded_image_name', 'blinded_image_filename',
                                  'image_filename', 'image_name', 'filename', 'file_name'], override.get('filename'), False)
    label_col = pick_column(frame, ['true_label', 'label', 'class_label', 'class', 'true_class', 'class_name',
                                   'target', 'seizure', 'is_seizure'], override.get('label'))
    if path_col is None and name_col is None:
        raise ValueError(f'{dataset}: image path/name column missing; columns={frame.columns.tolist()}')
    labels = frame[label_col].map(normalize_label).astype(int)
    for col in frame.columns:
        if col != label_col and norm(col) in {'truelabel', 'label', 'trueclass', 'classname', 'classlabel'}:
            other = frame[col].map(normalize_label).astype(int)
            if not np.array_equal(labels.to_numpy(), other.to_numpy()):
                raise ValueError(f'{dataset}: conflicting label columns {label_col!r} and {col!r}')
    output = []
    problems = []
    for position, (_, row) in enumerate(tqdm(frame.iterrows(), total=len(frame), desc=f'Validate {dataset}')):
        raw = clean_path(row[path_col]) if path_col else ''
        filename = clean_path(row[name_col]) if name_col else ''
        label = int(labels.iloc[position])
        try:
            if has_other_representation(raw):
                raise ValueError('CSV points to a different representation, not A1')
            pid, serial, edf, window = row_identity(row, frame, [raw, filename], forced_patient)
            path, method = resolver.resolve(raw, filename, pid, label, Path(csv_path).parent)
            actual_pid = metadata_patient_hints(path)
            if actual_pid and actual_pid != {pid}:
                raise ValueError('Resolved image patient does not match CSV patient')
            with Image.open(path) as image:
                image.verify()
            with Image.open(path) as image:
                rgb = image.convert('RGB')
                pixel_hash = hashlib.sha256(str(rgb.size).encode() + rgb.tobytes()).hexdigest()
            item = row.to_dict()
            item.update(patient_id=pid, label=label, source_image_path=path, image_path=path,
                        original_image_path=raw or filename, source_csv=str(csv_path), source_row=position,
                        row_uid=f'{dataset}:{position:08d}', dataset=dataset, image_match_method=method,
                        original_global_serial=serial, original_edf=edf, original_window=window,
                        pixel_sha256=pixel_hash)
            output.append(item)
        except Exception as error:
            problems.append({'dataset': dataset, 'csv': str(csv_path), 'source_row': position,
                             'original_image_path': raw or filename, 'error': f'{type(error).__name__}: {error}'})
    result = pd.DataFrame(output)
    if problems:
        return result, problems
    if set(result.label.unique()) != {0, 1}:
        raise ValueError(f'{dataset}: both classes are required')
    if result.source_image_path.duplicated().any():
        raise ValueError(f'{dataset}: multiple rows resolve to the same image')
    for colset in [('patient_id', 'original_global_serial'), ('patient_id', 'original_edf', 'original_window')]:
        identified = result[list(colset)].ne('').all(axis=1)
        if result.loc[identified, list(colset)].duplicated().any():
            raise ValueError(f'{dataset}: duplicate original window identifiers in {colset}')
    print(f'{dataset}: {len(result)} images; patients={sorted(result.patient_id.unique())}; '
          f'classes={result.label.value_counts().to_dict()}')
    return result, []


def canonical_window_keys(frame):
    keys = set()
    for row in frame.to_dict('records'):
        pid = row['patient_id']
        if row['original_global_serial']:
            keys.add(('global_serial', pid, row['original_global_serial']))
        if row['original_edf'] and row['original_window']:
            keys.add(('edf_window', pid, row['original_edf'], row['original_window']))
    return keys


def frame_fingerprint(frame):
    cols = ['row_uid', 'patient_id', 'label', 'original_global_serial', 'original_edf',
            'original_window', 'pixel_sha256']
    return object_sha256(frame[cols].to_dict('records'))


def audit_partitions(partitions, report_dir):
    import itertools
    reports, collisions, recording_overlap = [], [], []
    for (a, left), (b, right) in itertools.combinations(partitions.items(), 2):
        shared_paths = set(left.source_image_path) & set(right.source_image_path)
        shared_windows = canonical_window_keys(left) & canonical_window_keys(right)
        if shared_paths or shared_windows:
            raise ValueError(f'Data overlap between {a} and {b}: {len(shared_paths)} paths, '
                             f'{len(shared_windows)} original IDs; examples={list(shared_windows)[:5]}')
        reports.append({'partition_a': a, 'partition_b': b, 'shared_paths': 0, 'shared_window_ids': 0})
        shared_pixels = set(left.pixel_sha256) & set(right.pixel_sha256)
        for value in sorted(shared_pixels):
            collisions.append({'partition_a': a, 'partition_b': b, 'pixel_sha256': value,
                               'left_rows': '|'.join(left.loc[left.pixel_sha256 == value, 'row_uid']),
                               'right_rows': '|'.join(right.loc[right.pixel_sha256 == value, 'row_uid'])})
        left_edfs = set(zip(left.patient_id, left.original_edf)) - {(p, '') for p in left.patient_id.unique()}
        right_edfs = set(zip(right.patient_id, right.original_edf)) - {(p, '') for p in right.patient_id.unique()}
        for pid, edf in sorted(left_edfs & right_edfs):
            recording_overlap.append({'partition_a': a, 'partition_b': b, 'patient': pid, 'edf': edf})
    save_csv(Path(report_dir) / 'partition_overlap_audit.csv', pd.DataFrame(reports))
    save_csv(Path(report_dir) / 'identical_pixel_inputs.csv', pd.DataFrame(collisions, columns=[
        'partition_a', 'partition_b', 'pixel_sha256', 'left_rows', 'right_rows']))
    save_csv(Path(report_dir) / 'shared_recordings.csv', pd.DataFrame(recording_overlap, columns=[
        'partition_a', 'partition_b', 'patient', 'edf']))
    if collisions:
        print(f'NOTE: {len(collisions)} identical rendered-input matches across partitions. Original window IDs are '
              'distinct. See identical_pixel_inputs.csv; these may be representation collisions or copies requiring review.')
    if recording_overlap:
        print('NOTE: Some partitions share EDF recordings. This preserves your existing WINDOW-level pilot; '
              'it does not establish recording- or seizure-event-disjoint generalization. See shared_recordings.csv.')
    return reports

def seed_everything(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.backends.cuda.matmul.allow_tf32 = True


def build_model(run_dir):
    if not torch.cuda.is_available():
        raise RuntimeError('Select a GPU runtime in Colab before starting model training.')
    bf16 = torch.cuda.is_bf16_supported()
    if REQUIRE_BF16 and not bf16:
        raise RuntimeError('The reference uses BF16. Select a BF16-capable GPU, e.g. A100 or L4.')
    dtype = torch.bfloat16 if bf16 else torch.float16
    previous_traceback = getattr(sys, 'last_traceback', None)
    if previous_traceback is not None:
        traceback.clear_frames(previous_traceback)
    gc.collect()
    torch.cuda.empty_cache()
    seed_everything(SEED)
    model_info_file = Path(run_dir) / 'model_setup.json'
    prior = json.loads(model_info_file.read_text()) if model_info_file.is_file() else {}
    revision = prior.get('base_commit')
    if not isinstance(revision, str) or re.fullmatch(r'[0-9a-fA-F]{40}', revision) is None:
        raise ValueError('This model instance requires the resolved immutable base commit from preflight.')
    kwargs = {'revision': revision}
    processor = AutoProcessor.from_pretrained(MODEL_ID, token=True, **kwargs)
    quantization = BitsAndBytesConfig(load_in_4bit=True, bnb_4bit_quant_type='nf4',
        bnb_4bit_use_double_quant=True, bnb_4bit_compute_dtype=dtype,
        llm_int8_skip_modules=['model.vision_tower', 'model.multi_modal_projector', 'lm_head',
                              'vision_tower', 'multi_modal_projector', 'model.lm_head'])
    setup_start = phase_start()
    base = AutoModelForImageTextToText.from_pretrained(MODEL_ID, token=True, quantization_config=quantization,
        torch_dtype=dtype, device_map={'': 0}, attn_implementation='sdpa', **kwargs)
    reported_commit = getattr(base.config, '_commit_hash', None)
    if reported_commit is not None and reported_commit != revision:
        raise RuntimeError('The loaded model reports a revision different from the requested pin.')
    base = prepare_model_for_kbit_training(base, use_gradient_checkpointing=True,
        gradient_checkpointing_kwargs={'use_reentrant': False})
    for name, module in base.named_modules():
        if name.split('.')[-1] in {'vision_tower', 'multi_modal_projector'}:
            if any(isinstance(m, bnb.nn.Linear4bit) for m in module.modules()):
                raise RuntimeError('Vision/projector quantization exclusion failed.')
            module.to(dtype=dtype)
    candidates = [name for name, module in base.named_modules()
        if isinstance(module, (torch.nn.Linear, bnb.nn.Linear4bit))
        and name.split('.')[-1] in TARGET_LEAVES and 'vision' not in name.lower()]
    targets = [name for name in candidates if 'language_model' in name.lower()] or candidates
    if not targets:
        raise RuntimeError('No language q/k/v/o targets found.')
    quantized = [name for name, module in base.named_modules()
                 if name in targets and isinstance(module, bnb.nn.Linear4bit)]
    if set(quantized) != set(targets):
        raise RuntimeError('Every attention projection targeted by QLoRA must be 4-bit.')
    model = get_peft_model(base, LoraConfig(r=LORA_R, lora_alpha=LORA_ALPHA, lora_dropout=LORA_DROPOUT,
        target_modules=targets, bias='none', task_type='CAUSAL_LM'))
    del base
    if any(p.requires_grad and ('vision' in n.lower() or 'lora_' not in n)
           for n, p in model.named_parameters()):
        raise RuntimeError('Unexpected trainable parameters outside language attention LoRA.')
    trainable, total = model.get_nb_trainable_parameters()
    info = {'model_id': MODEL_ID, 'base_commit': revision,
            'base_commit_reported_by_config': reported_commit,
            'base_revision_resolution': prior.get('base_revision_resolution'),
            'trainable_parameters': int(trainable), 'total_logical_parameters': int(total),
            'trainable_percent': 100 * trainable / total, 'target_modules': targets,
            'compute_dtype': str(dtype), 'quantization_skip_modules': quantization.llm_int8_skip_modules,
            'gpu': torch.cuda.get_device_name(0), 'gpu_total_GiB': torch.cuda.get_device_properties(0).total_memory / 2**30,
            'versions': {'python': sys.version, 'torch': torch.__version__, 'transformers': transformers.__version__,
                         'peft': peft.__version__, 'bitsandbytes': bnb.__version__},
            'resources': phase_finish(setup_start)}
    if prior:
        if prior['target_modules'] != info['target_modules'] or prior['compute_dtype'] != info['compute_dtype']:
            raise RuntimeError('Resume architecture/precision differs from the original run.')
        info['original_setup'] = prior.get('original_setup', {k: v for k, v in prior.items() if k != 'original_setup'})
    save_json(model_info_file, info)
    (Path(run_dir) / 'target_modules.txt').write_text('\n'.join(targets), encoding='utf-8')
    model.print_trainable_parameters()
    print('GPU:', info['gpu'], '| dtype:', dtype)
    return model, processor, dtype


def adapter_file(adapter_dir):
    path = Path(adapter_dir) / 'adapter_model.safetensors'
    if not path.is_file():
        raise FileNotFoundError(f'Adapter weights not found: {path}')
    return path


def load_adapter_exact(model, adapter_dir):
    state = load_file(str(adapter_file(adapter_dir)), device='cpu')
    expected = get_peft_model_state_dict(model)
    if set(state) != set(expected):
        raise RuntimeError('Checkpoint adapter keys do not match the active adapter.')
    for key in expected:
        if state[key].shape != expected[key].shape:
            raise RuntimeError(f'Checkpoint tensor shape mismatch: {key}')
    result = set_peft_model_state_dict(model, state, adapter_name='default')
    if result.unexpected_keys:
        raise RuntimeError(f'Unexpected checkpoint keys: {result.unexpected_keys}')
    loaded = get_peft_model_state_dict(model)
    for key, tensor in state.items():
        if not torch.equal(loaded[key].detach().cpu(), tensor):
            raise RuntimeError(f'Exact adapter reload verification failed for {key}')
    del state, expected, loaded
    gc.collect()
    torch.cuda.empty_cache()
    return file_sha256(adapter_file(adapter_dir))


def completed_stage(stage_dir, expected_signature):
    marker = Path(stage_dir) / 'completed.json'
    if not marker.is_file():
        return None
    record = json.loads(marker.read_text())
    if record['stage_signature'] != expected_signature:
        raise RuntimeError('Completed training stage does not match this protocol or initialization.')
    if file_sha256(adapter_file(record['best_adapter'])) != record['adapter_sha256']:
        raise RuntimeError('Saved best adapter changed after completion.')
    print(f'Reusing completed {record["stage"]}: {record["best_adapter"]}')
    return record

def valid_only_metrics(truth, predictions):
    selected = [(int(y), int(p)) for y, p in zip(truth, predictions) if p is not None]
    counts = {'TN': 0, 'FP': 0, 'FN': 0, 'TP': 0}
    for y, p in selected:
        key = 'TN' if y == 0 and p == 0 else 'FP' if y == 0 else 'TP' if p == 1 else 'FN'
        counts[key] += 1
    tn, fp, fn, tp = (counts[k] for k in ['TN', 'FP', 'FN', 'TP'])
    sensitivity = tp / (tp + fn) if tp + fn else None
    specificity = tn / (tn + fp) if tn + fp else None
    return {'valid_predictions': len(selected), **counts,
            'accuracy': (tn + tp) / len(selected) if selected else None,
            'sensitivity': sensitivity, 'specificity': specificity,
            'balanced_accuracy': (sensitivity + specificity) / 2 if sensitivity is not None and specificity is not None else None}


