class TrackedCollator(Collator):
    def __call__(self, rows):
        return {'batch': super().__call__(rows), 'row_uid': rows[0]['row_uid'],
                'patient_id': rows[0]['patient_id'], 'label': int(rows[0]['label'])}


def adapter_tensor_hash(model):
    h = hashlib.sha256()
    for name, tensor in sorted(get_peft_model_state_dict(model).items()):
        value = tensor.detach().cpu().contiguous()
        h.update(name.encode())
        h.update(str(value.dtype).encode())
        h.update(str(tuple(value.shape)).encode())
        h.update(value.view(torch.uint8).numpy().tobytes())
    return h.hexdigest()


