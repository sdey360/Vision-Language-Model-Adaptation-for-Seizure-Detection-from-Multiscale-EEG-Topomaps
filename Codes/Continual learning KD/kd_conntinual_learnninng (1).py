    for name in ('stage1_train', 'stage1_validation', 'stage2_train', 'stage2_validation',
                 *('test_' + p for p in TEST_CSVS)):
        if not (directory / 'splits' / (name + '.csv')).is_file():
            raise FileNotFoundError('Source split is missing: ' + name)
