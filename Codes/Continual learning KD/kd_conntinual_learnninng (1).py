def resolve_source_run():
    if BASELINE_RUN_DIR.strip():
        return validate_source_run(BASELINE_RUN_DIR.strip(), verify_weights=True)
    requested_adapter = globals().get('OLD_ADAPTER_DIR')
    if requested_adapter:
        requested_adapter = Path(requested_adapter)
        if not requested_adapter.is_dir():
            raise FileNotFoundError('Your supplied old adapter directory is missing: ' + str(requested_adapter))
        if requested_adapter.name != 'best_adapter' or requested_adapter.parents[2].name != 'stage1_old_patients':
            raise ValueError('OLD_ADAPTER_DIR must be a Stage 1 attempts/<timestamp>/best_adapter directory.')
        return validate_source_run(requested_adapter.parents[3], verify_weights=True)
    candidates, rejected = [], []
    root = Path(BASELINE_SEARCH_ROOT)
    for marker in sorted(root.glob('*/stage1_old_patients/completed.json')):
        directory = marker.parent.parent
        try:
            candidates.append(validate_source_run(directory))
        except Exception as error:
            rejected.append({'directory': str(directory), 'reason': str(error)})
    identities = defaultdict(list)
    for item in candidates:
        key = object_sha256({'adapter': item['completed']['adapter_sha256'],
                             'partitions': item['manifest']['partition_fingerprints'],
                             'base_commit': item['setup']['base_commit']})
        identities[key].append(item)
    if len(identities) != 1:
        print('Compatible completed old-patient runs:')
        for item in candidates:
            print(str(item['directory']))
        if rejected:
            print('Rejected candidates:', json.dumps(rejected, indent=2))
        raise ValueError('Set BASELINE_RUN_DIR to your successful A1 forgetting run. '
                         'Automatic selection requires one unique compatible checkpoint/split identity; '
                         'failed preflight run directories are not completed checkpoints.')
    selected = sorted(next(iter(identities.values())), key=lambda x: str(x['directory']))[-1]
    print('Verified source run:', selected['directory'])
    return validate_source_run(selected['directory'], verify_weights=True)


def read_source_split(path, expected_fingerprint):
    strings = {k: str for k in ['row_uid', 'patient_id', 'original_global_serial',
                               'original_edf', 'original_window', 'pixel_sha256']}
    frame = pd.read_csv(path, keep_default_na=False, dtype=strings)
    frame['label'] = frame.label.map(normalize_label).astype(int)
    frame['patient_id'] = frame.patient_id.map(lambda x: f'{int(x):02d}')
    if frame.empty or frame.row_uid.duplicated().any():
        raise ValueError(f'Empty or duplicate row identities in {path}')
    if frame_fingerprint(frame) != expected_fingerprint:
        raise ValueError(f'Saved split differs from the source training manifest: {path}')
    return frame


def validate_saved_images(partitions, source, report_dir):
    # Use the source run's RESOLVED splits. Original blinded counters are never treated as window IDs.
    resolver, problems, relocation = None, [], []
    globals().setdefault('ACTIVE_PATIENT_PREFIXES', {}).update(
        {str(k).lower(): {f'{int(v):02d}'} for k, v in PATIENT_FILENAME_PREFIXES.items()})
    for name, frame in partitions.items():
        for idx, row in tqdm(frame.iterrows(), total=len(frame), desc='Verify ' + name):
            try:
                original = clean_path(row['source_image_path'])
                path = Path(original)
                if not path.is_file():
                    if resolver is None:
                        resolver = A1ImageResolver(IMAGE_SEARCH_ROOTS)
                    found, method = resolver.resolve(original, Path(original).name,
                                                     row.patient_id, int(row.label))
                    path = Path(found)
                    relocation.append({'partition': name, 'row_uid': row.row_uid,
                                       'old_path': original, 'resolved_path': str(path), 'method': method})
                if not explicit_a1_image(path):
                    raise ValueError('Resolved image has no positive A1 folder evidence.')
                with Image.open(path) as opened:
                    rgb = opened.convert('RGB')
                    digest = hashlib.sha256(str(rgb.size).encode() + rgb.tobytes()).hexdigest()
                if digest != row.pixel_sha256:
                    raise ValueError('Decoded pixels differ from the image used in the source run.')
                frame.at[idx, 'source_image_path'] = str(path)
                frame.at[idx, 'image_path'] = str(path)
            except Exception as error:
                problems.append({'partition': name, 'row_uid': row.row_uid,
                                 'path': row.source_image_path, 'error': str(error)})
    save_csv(Path(report_dir) / 'relocated_images.csv', pd.DataFrame(relocation))
    if problems:
        save_csv(Path(report_dir) / 'image_problems.csv', pd.DataFrame(problems))
        print(pd.DataFrame(problems).head(15).to_string(index=False))
        raise RuntimeError('Image verification failed. No model has been loaded and no rows were dropped.')


def select_replay_memory(old_train):
    chosen, audit = [], []
    for patient in OLD_PATIENTS:
        for label in (0, 1):
            candidates = old_train[(old_train.patient_id == patient) & (old_train.label == label)].copy()
            seed = MEMORY_SEED + int(patient) * 10 + label
            candidates = candidates.sample(frac=1, random_state=seed).reset_index(drop=True)
            # Identical rendered images do not consume several slots in the same patient/class stratum.
            candidates = candidates.drop_duplicates('pixel_sha256').reset_index(drop=True)
            if len(candidates) < MEMORY_PER_PATIENT_CLASS:
                raise ValueError(f'Patient {patient}, label {label}: need {MEMORY_PER_PATIENT_CLASS} '
                                 f'distinct rendered training images, found {len(candidates)}.')
            def group_key(row):
                for key in ('original_edf', 'edf_file', 'edf_filename', 'recording_id'):
                    value = str(row.get(key, '')).strip()
                    if value and value.lower() not in {'nan', 'none'}:
                        return value
                return '__no_recording_metadata__'
            candidates['_memory_group'] = candidates.apply(group_key, axis=1)
            queues = [g.to_dict('records') for _, g in candidates.groupby('_memory_group', sort=True)]
            rng = random.Random(seed)
            rng.shuffle(queues)
            picked = []
            # Round-robin across known recordings, randomly within each recording.
            # With no EDF metadata this is reproducible random sampling, not an event-diversity claim.
            while len(picked) < MEMORY_PER_PATIENT_CLASS:
                for queue in queues:
                    if queue and len(picked) < MEMORY_PER_PATIENT_CLASS:
                        picked.append(queue.pop())
            for item in picked:
                item['memory_source_group'] = item.pop('_memory_group')
            chosen.extend(picked)
            audit.append({'patient_id': patient, 'label': label, 'training_candidates': int(
                ((old_train.patient_id == patient) & (old_train.label == label)).sum()),
                'distinct_pixel_candidates': len(candidates), 'selected': len(picked),
                'recording_groups_available': len(queues),
                'recording_metadata_available': bool(candidates['_memory_group'].ne('__no_recording_metadata__').any())})
    memory = pd.DataFrame(chosen).sample(frac=1, random_state=MEMORY_SEED).reset_index(drop=True)
    if memory.row_uid.duplicated().any() or len(memory) != 6 * MEMORY_PER_PATIENT_CLASS:
        raise RuntimeError('Replay selection violated its unique-example budget.')
    if not set(memory.row_uid).issubset(set(old_train.row_uid)) or NEW_PATIENT in set(memory.patient_id):
        raise RuntimeError('Replay selection includes data outside old TRAINING splits.')
    return memory, pd.DataFrame(audit)


def replay_slots(n_new, n_memory):
    if n_new <= 0 or n_memory < 0:
        raise ValueError('Need positive new-example count and nonnegative memory size.')
    # Slot i contains old indices scheduled AFTER new microbatch i. Every memory index occurs once.
    return [list(range(i * n_memory // n_new, (i + 1) * n_memory // n_new)) for i in range(n_new)]


def selection_update(ba, loss, best_ba, best_loss, stale):
    strict = ba > best_ba + 1e-12
    tie = math.isclose(ba, best_ba, rel_tol=0, abs_tol=1e-12)
    save_best = strict or (tie and loss < best_loss)
    return save_best, (0 if strict else stale + 1)


