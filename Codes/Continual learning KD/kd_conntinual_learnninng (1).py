def norm(value):
    return re.sub(r"[^a-z0-9]", "", str(value).lower())


def clean_path(value):
    if pd.isna(value):
        return ""
    return str(value).strip().strip('"').strip("'").replace("\\", "/")


def normalize_label(value):
    literal = str(value).strip().lower()
    if literal in {"0", "0.0"}:
        return 0
    if literal in {"1", "1.0"}:
        return 1
    s = norm(value)
    if s in {"nonseizure", "normal", "interictal", "ns", "false"}:
        return 0
    if s in {"seizure", "ictal", "sz", "true"}:
        return 1
    raise ValueError(f"Unknown label {value!r}; expected 0=non-seizure, 1=seizure.")


def pick_column(df, names, override=None, required=True):
    if override:
        if override not in df.columns:
            raise ValueError(f"Column {override!r} is missing. Available: {df.columns.tolist()}")
        return override
    normalized = {norm(c): c for c in df.columns}
    for name in names:
        if norm(name) in normalized:
            return normalized[norm(name)]
    if required:
        raise ValueError(f"Cannot identify column from {names}. Available: {df.columns.tolist()}")
    return None


def patient_hints(value):
    # Never infer identity from a bare number such as the window serial.
    return {f"{int(x):02d}" for x in re.findall(
        r"(?:pati+ent|patient|chb)[ _-]*0*(\d{1,2})(?!\d)", str(value), re.I
    )}


def has_other_representation(value):
    p = Path(clean_path(value))
    text = str(p.parent) if p.suffix.lower() in IMAGE_SUFFIXES else str(p)
    # A1 folders are allowed. Reject RAW and other DWT representations.
    if re.search(r"(?:^|[^a-z0-9])raw(?:[^a-z0-9]|$)", text, re.I):
        return True
    representations = re.findall(
        r"(?:^|[^a-z0-9])(a[1-5](?:d[1-5])*)(?=[^a-z0-9]|$)", text, re.I
    )
    return any(token.casefold() != "a1" for token in representations)


def signature(value):
    text = str(value).replace("\\", "/").split("/")[-1]
    patients = patient_hints(text)
    patient = next(iter(patients)) if len(patients) == 1 else None
    g = re.search(r"(?:^|[_\- ])G(\d+)(?=[_\- .]|$)", text, re.I)
    w = re.search(r"(?:^|[_\- ])W(\d+)(?=[_\- .]|$)", text, re.I)
    edf = re.search(r"chb\d{2}_\d+(?:\+)?(?=[_\-.]|$)", text, re.I)
    return patient, int(g[1]) if g else None, int(w[1]) if w else None, edf[0].lower() if edf else None


def folder_label(path):
    labels = {normalize_label(part) for part in Path(path).parent.parts
              if norm(part) in {"nonseizure", "seizure", "interictal", "ictal"}}
    if len(labels) > 1:
        raise ValueError(f"Conflicting class folders: {path}")
    return next(iter(labels)) if labels else None


class ImageResolver:
    def __init__(self, roots, key):
        self.key = key
        self.roots = [Path(clean_path(p)) for p in roots]
        self.by_name = defaultdict(list)
        self.by_pg = defaultdict(list)
        self.by_pew = defaultdict(list)
        files = set()
        for root in self.roots:
            if not root.is_dir():
                raise FileNotFoundError(f"{key}: image folder does not exist: {root}")
            for directory, dirs, names in os.walk(root):
                dirs[:] = [d for d in dirs if not d.startswith(".") and not has_other_representation(Path(directory) / d)]
                for name in names:
                    p = Path(directory) / name
                    if p.suffix.lower() in IMAGE_SUFFIXES and not has_other_representation(p):
                        files.add(p.resolve())
        for p in sorted(files):
            self.by_name[p.name.casefold()].append(p)
            pid, g, w, edf = signature(p.name)
            if pid and g is not None:
                self.by_pg[(pid, g)].append(p)
            if pid and edf and w is not None:
                self.by_pew[(pid, edf, w)].append(p)
        self.files = files
        print(f"{key}: indexed {len(files)} images in {[str(p) for p in self.roots]}")

    def choose(self, candidates, pid, label, method):
        valid = []
        for p in sorted(set(candidates)):
            hints = patient_hints(str(p))
            if pid and hints and hints != {pid}:
                continue
            actual_label = folder_label(p)
            if actual_label is not None and actual_label != label:
                continue
            valid.append(p)
        if len(valid) == 1:
            return str(valid[0]), method
        if len(valid) > 1:
            raise ValueError(f"Ambiguous {method} match: {[str(p) for p in valid[:6]]}")
        return None

    def resolve(self, raw, filename, pid, label):
        raw = clean_path(raw)
        filename = clean_path(filename).split("/")[-1] if filename else ""
        basename = raw.split("/")[-1] or filename
        names = list(dict.fromkeys(n for n in [basename, filename] if n))
        if not names:
            raise FileNotFoundError("Empty image path and filename")
        # An existing direct path is accepted only within this dataset's roots.
        p = Path(raw)
        if raw.startswith("/") and p.is_file() and p.resolve() in self.files:
            chosen = self.choose([p.resolve()], pid, label, "existing Drive path")
            if chosen:
                return chosen
        exact = [p for n in names for p in self.by_name.get(n.casefold(), [])]
        chosen = self.choose(exact, pid, label, "exact filename")
        if chosen:
            return chosen
        # Known representation-token change, confined to the supplied A1 roots.
        aliases = {re.sub(r"(?<![a-z0-9])raw(?![a-z0-9])", "A1", n, flags=re.I)
                   for n in names}
        aliased = [p for n in aliases for p in self.by_name.get(n.casefold(), [])]
        chosen = self.choose(aliased, pid, label, "RAW-to-A1 filename token")
        if chosen:
            return chosen
        # Renamed files: require patient + global serial, and match window/EDF
        # identifiers as well whenever the source filename supplies them.
        for n in names:
            source_pid, g, w, edf = signature(n)
            expected_pid = pid or source_pid
            if source_pid and pid and source_pid != pid:
                raise ValueError(f"Patient metadata disagrees with filename: {n}")
            if expected_pid and g is not None:
                candidates = self.by_pg.get((expected_pid, g), [])
            elif expected_pid and edf and w is not None:
                candidates = self.by_pew.get((expected_pid, edf, w), [])
            else:
                continue
            candidates = [p for p in candidates
                if (w is None or signature(p.name)[2] == w)
                and (edf is None or signature(p.name)[3] == edf)]
            chosen = self.choose(candidates, expected_pid, label, "patient/window identifiers")
            if chosen:
                return chosen
        raise FileNotFoundError(f"No unique matching image in this dataset's image folders: {raw or filename}")


def split_pool(pool):
    # Exact per-class shuffle/ceil/tail split from your saved pooled LoRA code.
    training_parts, validation_parts = [], []
    for label in (0, 1):
        group = pool[pool.label == label].sample(frac=1, random_state=SEED)
        if len(group) < 2:
            raise ValueError("Need at least two pooled examples per class.")
        n_val = max(1, min(len(group) - 1, math.ceil(len(group) * VAL_FRACTION)))
        training_parts.append(group.iloc[:-n_val])
        validation_parts.append(group.iloc[-n_val:])
    return tuple(pd.concat(parts).sample(frac=1, random_state=SEED).reset_index(drop=True)
                 for parts in (training_parts, validation_parts))


