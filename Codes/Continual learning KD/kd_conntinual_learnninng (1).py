def answer_logits(output, labels):
    if output.logits.shape[:2] != labels.shape:
        raise RuntimeError('Expected full-sequence logits for the exact reference masked CE objective.')
    mask = labels[:, 1:].ne(-100)
    if not bool(mask.any()):
        raise ValueError('No assistant answer tokens are available for distillation.')
    # Position j predicts label j+1. Boolean indexing copies only supervised answer positions.
    return output.logits[:, :-1, :][mask].float(), labels[:, 1:][mask]


def answer_kl(student_logits, teacher_logits):
    if student_logits.shape != teacher_logits.shape or student_logits.ndim != 2:
        raise ValueError('Teacher and student need matching [answer_tokens, vocabulary] logits.')
    temperature = KD_TEMPERATURE
    student_logp = torch.nn.functional.log_softmax(student_logits.float() / temperature, dim=-1)
    teacher_logp = torch.nn.functional.log_softmax(teacher_logits.detach().float() / temperature, dim=-1)
    # batchmean on [answer_tokens, vocabulary] sums vocabulary KL, averages answer positions.
    value = torch.nn.functional.kl_div(student_logp, teacher_logp,
                                     reduction='batchmean', log_target=True) * temperature**2
    if not torch.isfinite(value).item() or float(value.detach()) < -1e-4:
        raise FloatingPointError('Invalid distillation loss.')
    return value.clamp_min(0.0)  # Remove tiny negative roundoff, not a negative mathematical KL.


def smoke_check(student, teacher, processor, dtype, prepared):
    # Forward-only check on TRAINING memory; never use a test image to debug the training objective.
    student.eval()
    row = prepared['new_train' if METHOD == 'new_only' else 'memory'].iloc[0].to_dict()
    batch = to_gpu(Collator(processor)([row]), dtype)
    with torch.no_grad(), torch.autocast('cuda', dtype=dtype):
        output = student(**batch, use_cache=False)
        slogits, targets = answer_logits(output, batch['labels'])
        explicit_ce = torch.nn.functional.cross_entropy(slogits, targets)
        if not torch.allclose(output.loss.float(), explicit_ce, atol=3e-4, rtol=3e-4):
            raise RuntimeError('Full-answer CE mask does not match the reference model loss.')
        record = {'row_uid': row['row_uid'], 'answer_token_ids': targets.cpu().tolist(),
                  'answer_text': processor.tokenizer.decode(targets.cpu().tolist()),
                  'supervised_answer_tokens': int(len(targets)), 'student_ce': float(explicit_ce),
                  'student_adapter_tensor_sha256': adapter_tensor_hash(student)}
        del output
        if teacher is not None:
            teacher.eval()
            output = teacher(**batch, use_cache=False)
            tlogits, ttargets = answer_logits(output, batch['labels'])
            if not torch.equal(targets, ttargets):
                raise RuntimeError('Teacher/student answer-token positions disagree.')
            difference = float((slogits - tlogits).abs().max())
            kd = float(answer_kl(slogits, tlogits))
            if not torch.allclose(slogits, tlogits, atol=1e-4, rtol=1e-4) or kd > 1e-4:
                raise RuntimeError('Teacher/student do not start with matching eval-mode responses.')
            if record['student_adapter_tensor_sha256'] != adapter_tensor_hash(teacher):
                raise RuntimeError('Teacher/student adapter initializations differ.')
            record.update(initial_kd=kd, max_logit_difference=difference,
                          teacher_frozen=not any(p.requires_grad for p in teacher.parameters()))
            del output, tlogits, ttargets
    del slogits, targets, batch
    save_json(prepared['run_dir'] / 'smoke_check.json', record)
    print('Initial full-answer CE/KD check passed:', record)
    return record


