def train_continual_student(student, teacher, processor, dtype, prepared):
    stage_dir = prepared['run_dir'] / 'student_training'
    signature = object_sha256({'protocol_hash': prepared['protocol_hash'],
                              'initialization': prepared['source']['completed']['adapter_sha256']})
    existing = completed_stage(stage_dir, signature)
    if existing is not None:
        load_adapter_exact(student, existing['best_adapter'])
        return existing
    load_adapter_exact(student, prepared['initial_adapter'])
    attempt = stage_dir / 'attempts' / datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S_%f_UTC')
    attempt.mkdir(parents=True, exist_ok=False)
    best_dir = attempt / 'best_adapter'
    seed_everything(SEED)
    student.gradient_checkpointing_enable(gradient_checkpointing_kwargs={'use_reentrant': False})
    set_training_cache(student, False)
    params = [p for p in student.parameters() if p.requires_grad]
    if not params or any(p.requires_grad and 'lora_' not in n for n, p in student.named_parameters()):
        raise RuntimeError('Only the student LoRA parameters may be trained.')
    if METHOD == 'replay_kd' and (teacher is None or any(p.requires_grad for p in teacher.parameters())):
        raise RuntimeError('KD requires a completely frozen teacher.')
    teacher_initial = adapter_tensor_hash(teacher) if teacher is not None else None
    generator = torch.Generator().manual_seed(SEED)
    loader = DataLoader(Topomaps(prepared['new_train']), batch_size=1, shuffle=True,
                        generator=generator, num_workers=NUM_WORKERS, collate_fn=TrackedCollator(processor))
    val_loader = DataLoader(Topomaps(prepared['new_val']), batch_size=1, shuffle=False,
                            num_workers=NUM_WORKERS, collate_fn=Collator(processor))
    optimizer = torch.optim.AdamW(params, lr=STAGE2_LR, weight_decay=WEIGHT_DECAY)
    steps_per_epoch = math.ceil(len(loader) / GRAD_ACCUM)
    total_steps = steps_per_epoch * STAGE2_MAX_EPOCHS
    scheduler = get_linear_schedule_with_warmup(optimizer,
        num_warmup_steps=math.ceil(total_steps * WARMUP_RATIO), num_training_steps=total_steps)
    scaler = torch.amp.GradScaler('cuda', enabled=dtype == torch.float16)
    old_collator = Collator(processor)
    history, old_history, exposures = [], [], []
    training_resources, validation_resources, checkpoint_resources = [], [], []
    best_ba, best_loss, best_epoch, stale = -1.0, math.inf, None, 0
    started = time.perf_counter()
    optimizer_updates, skipped_updates = 0, 0
    audit = {'status': 'training', 'stage_signature': signature, 'method': METHOD,
             'initialization_sha256': prepared['source']['completed']['adapter_sha256'],
             'teacher_initial_tensor_sha256': teacher_initial,
             'optimizer_reinitialized': True, 'adapter_reinitialized': False,
             'new_examples_per_update': GRAD_ACCUM, 'replay_passes_per_epoch': 0 if METHOD == 'new_only' else 1,
             'test_data_used_for_training_or_selection': False,
             'checkpoint_rule': 'Patient11 validation BA; lower validation CE breaks BA ties',
             'time_definition': 'Training-loop time includes live teacher; validation/checkpoint IO logged separately',
             'memory_definition': 'PyTorch allocator total peaks, including both resident models when KD is active'}
    save_json(attempt / 'resource_summary.json', audit)
    try:
        for epoch in range(1, STAGE2_MAX_EPOCHS + 1):
            student.train()
            set_training_cache(student, False)
            if teacher is not None:
                teacher.eval()
            memory = prepared['memory'].sample(frac=1, random_state=MEMORY_SEED + epoch).reset_index(drop=True)
            if METHOD == 'new_only':
                memory = memory.iloc[:0]
            slots = replay_slots(len(loader), len(memory))
            iterator = iter(loader)
            progress = tqdm(total=len(loader), desc=f'{METHOD} epoch {epoch}/{STAGE2_MAX_EPOCHS}')
            new_sum, old_sum, kd_sum, objective_sum = 0.0, 0.0, 0.0, 0.0
            replay_seen, new_seen, teacher_forwards, first_gradient_audited = [], [], 0, False
            schedule_rows = []
            measured = phase_start()
            for group_start in range(0, len(loader), GRAD_ACCUM):
                group_end = min(group_start + GRAD_ACCUM, len(loader))
                new_count = group_end - group_start
                old_count = sum(len(slots[i]) for i in range(group_start, group_end))
                optimizer.zero_grad(set_to_none=True)
                for index in range(group_start, group_end):
                    packed = next(iterator)
                    new_seen.append(packed['row_uid'])
                    batch = to_gpu(packed['batch'], dtype)
                    with torch.autocast('cuda', dtype=dtype):
                        output = student(**batch, use_cache=False)
                        new_loss = output.loss
                    if not torch.isfinite(new_loss).item():
                        raise FloatingPointError('Nonfinite Patient11 CE loss.')
                    value = float(new_loss.detach())
                    new_sum += value
                    objective_sum += value / new_count
                    scaler.scale(new_loss / new_count).backward()
                    schedule_rows.append({'kind': 'new', 'new_batch': index + 1,
                        'optimizer_group': group_start // GRAD_ACCUM + 1,
                        'row_uid': packed['row_uid'], 'patient_id': NEW_PATIENT, 'label': packed['label']})
                    del output, new_loss, batch, packed
                    for memory_index in slots[index]:
                        row = memory.iloc[memory_index].to_dict()
                        batch = to_gpu(old_collator([row]), dtype)
                        teacher_logits = None
                        if METHOD == 'replay_kd':
                            with torch.no_grad(), torch.autocast('cuda', dtype=dtype):
                                teacher_output = teacher(**batch, use_cache=False)
                                teacher_logits, _ = answer_logits(teacher_output, batch['labels'])
                            del teacher_output
                            teacher_forwards += 1
                        with torch.autocast('cuda', dtype=dtype):
                            output = student(**batch, use_cache=False)
                            replay_loss = output.loss
                            if METHOD == 'replay_kd':
                                student_logits, _ = answer_logits(output, batch['labels'])
                                kd_loss = answer_kl(student_logits, teacher_logits)
                            else:
                                kd_loss = replay_loss.new_zeros(())
                            old_loss = REPLAY_WEIGHT * replay_loss + (
                                KD_WEIGHT * kd_loss if METHOD == 'replay_kd' else 0)
                        if not torch.isfinite(old_loss).item():
                            raise FloatingPointError('Nonfinite old-label/KD loss.')
                        old_sum += float(replay_loss.detach())
                        kd_sum += float(kd_loss.detach())
                        objective_sum += float(old_loss.detach()) / old_count
                        scaler.scale(old_loss / old_count).backward()
                        replay_seen.append(row['row_uid'])
                        schedule_rows.append({'kind': 'replay', 'new_batch': index + 1,
                            'optimizer_group': group_start // GRAD_ACCUM + 1,
                            'row_uid': row['row_uid'], 'patient_id': row['patient_id'], 'label': int(row['label'])})
                        if METHOD == 'replay_kd':
                            del student_logits
                        del output, replay_loss, kd_loss, old_loss, teacher_logits, batch
                    progress.update(1)
                    progress.set_postfix(new_ce=f'{new_sum / len(new_seen):.4f}', replay=len(replay_seen))
                scaler.unscale_(optimizer)
                norm = torch.nn.utils.clip_grad_norm_(params, MAX_GRAD_NORM)
                if not torch.isfinite(norm).item():
                    raise FloatingPointError('Nonfinite adapter gradient norm.')
                if not first_gradient_audited:
                    nonzero = [n for n, p in student.named_parameters() if p.requires_grad and p.grad is not None
                               and bool(torch.count_nonzero(p.grad))]
                    forbidden = [n for n, p in student.named_parameters() if 'lora_' not in n and p.grad is not None]
                    if not nonzero or forbidden:
                        raise RuntimeError('Adapter gradient-flow check failed.')
                    save_json(attempt / f'gradient_audit_epoch_{epoch:03d}.json', {
                        'nonzero_student_adapter_tensors': len(nonzero), 'examples': nonzero[:8],
                        'unexpected_frozen_parameter_gradients': forbidden,
                        'teacher_has_any_gradient': teacher is not None and any(p.grad is not None for p in teacher.parameters())})
                    first_gradient_audited = True
                previous_scale = scaler.get_scale()
                scaler.step(optimizer)
                scaler.update()
                if scaler.get_scale() >= previous_scale:
                    scheduler.step()
                    optimizer_updates += 1
                else:
                    skipped_updates += 1
                optimizer.zero_grad(set_to_none=True)
            progress.close()
            if len(new_seen) != len(prepared['new_train']) or set(new_seen) != set(prepared['new_train'].row_uid):
                raise RuntimeError('Patient11 examples were skipped or duplicated within the epoch.')
            if len(replay_seen) != len(memory) or len(set(replay_seen)) != len(memory) or set(replay_seen) != set(memory.row_uid):
                raise RuntimeError('Replay must present every selected old image exactly once per epoch.')
            if teacher is not None and (adapter_tensor_hash(teacher) != teacher_initial or
                                       any(p.grad is not None for p in teacher.parameters())):
                raise RuntimeError('The frozen teacher changed or accumulated gradients.')
            training_resources.append(phase_finish(measured))
            save_csv(attempt / 'schedules' / f'epoch_{epoch:03d}.csv', pd.DataFrame(schedule_rows))
            exposures.append({'epoch': epoch, 'new_presentations': len(new_seen),
                             'replay_presentations': len(replay_seen), 'unique_replay_images': len(set(replay_seen)),
                             'teacher_forward_passes': teacher_forwards, 'optimizer_groups': steps_per_epoch})
            save_csv(attempt / 'epoch_exposure_summary.csv', pd.DataFrame(exposures))
            measured = phase_start()
            new_val_loss = validation_loss(student, val_loader, dtype)
            metrics, predictions = generate_predictions(student, processor, prepared['new_val'], dtype,
                                                         f'Patient11 validation epoch {epoch}')
            save_csv(attempt / 'validation' / f'epoch_{epoch:03d}_patient11.csv', predictions)
            diagnostics = old_validation_diagnostics(student, processor, prepared, dtype, epoch, attempt)
            old_history.extend(diagnostics)
            save_csv(attempt / 'old_validation_history.csv', pd.DataFrame(old_history))
            old_ba = float(np.mean([r['balanced_accuracy'] for r in diagnostics]))
            memory_ba = None
            if MONITOR_MEMORY_GENERATION:
                memory_metrics, memory_predictions = generate_predictions(student, processor, prepared['memory'], dtype,
                                                                            f'Replay-memory diagnostic epoch {epoch}')
                memory_ba = memory_metrics['balanced_accuracy']
                save_csv(attempt / 'validation' / f'epoch_{epoch:03d}_memory.csv', memory_predictions)
            validation_resources.append(phase_finish(measured))
            ba = metrics['balanced_accuracy']
            save_best, stale = selection_update(ba, new_val_loss, best_ba, best_loss, stale)
            if save_best:
                best_ba, best_loss, best_epoch = ba, new_val_loss, epoch
                measured = phase_start()
                student.save_pretrained(best_dir, safe_serialization=True)
                processor.save_pretrained(best_dir)
                save_csv(attempt / 'best_validation_predictions.csv', predictions)
                save_json(attempt / 'best_checkpoint.json', {'epoch': epoch, 'patient11_validation_ba': ba,
                    'patient11_validation_loss': new_val_loss, 'old_macro_validation_ba_diagnostic': old_ba,
                    'selection_uses_old_validation': False, 'adapter_path': str(best_dir)})
                checkpoint_resources.append(phase_finish(measured))
            record = {'epoch': epoch, 'new_label_loss': new_sum / len(loader),
                      'replay_label_loss': old_sum / len(memory) if len(memory) else None,
                      'kd_loss': kd_sum / len(memory) if METHOD == 'replay_kd' else None,
                      'mean_optimizer_group_objective': objective_sum / steps_per_epoch,
                      'new_validation_loss': new_val_loss,
                      **{'new_validation_' + k: v for k, v in metrics.items()},
                      'old_macro_validation_ba_diagnostic': old_ba,
                      'replay_memory_ba_diagnostic': memory_ba,
                      'balanced_old_new_score_DIAGNOSTIC_ONLY': (ba + old_ba) / 2,
                      'saved_best': save_best, 'epochs_without_ba_improvement': stale,
                      'learning_rate': scheduler.get_last_lr()[0],
                      'new_presentations': len(new_seen), 'replay_presentations': len(replay_seen),
                      **{'training_' + k: v for k, v in training_resources[-1].items()},
                      **{'validation_resource_' + k: v for k, v in validation_resources[-1].items()}}
            history.append(record)
            save_csv(attempt / 'training_history.csv', pd.DataFrame(history))
            audit.update(epochs_completed=epoch, best_epoch=best_epoch,
                optimizer_updates=optimizer_updates, skipped_updates=skipped_updates,
                training_loop=aggregate_phases(training_resources), validation=aggregate_phases(validation_resources),
                checkpoint_io=aggregate_phases(checkpoint_resources),
                overall_peak=aggregate_phases(training_resources + validation_resources + checkpoint_resources),
                training_wall_seconds=time.perf_counter() - started)
            save_json(attempt / 'resource_summary.json', audit)
            print(f'Epoch {epoch}: new BA={ba:.4f}; old validation macro BA={old_ba:.4f} (diagnostic); '
                  f'best epoch={best_epoch}; patience={stale}/{PATIENCE}')
            if stale >= PATIENCE:
                break
    except BaseException as error:
        audit.update(status='interrupted', error=f'{type(error).__name__}: {error}',
                     training_wall_seconds=time.perf_counter() - started)
        save_json(attempt / 'resource_summary.json', audit)
        raise
    finally:
        del optimizer, scheduler, scaler, params, loader, val_loader
        gc.collect()
        torch.cuda.empty_cache()
    adapter_sha = load_adapter_exact(student, best_dir)
    changed = adapter_change_report(prepared['initial_adapter'], best_dir)
    if changed['changed_adapter_elements'] == 0:
        raise RuntimeError('Training completed without any adapter-weight change.')
    save_json(attempt / 'adapter_change.json', changed)
    audit.update(status='completed', training_wall_seconds=time.perf_counter() - started,
                 teacher_final_tensor_sha256=adapter_tensor_hash(teacher) if teacher is not None else None)
    save_json(attempt / 'resource_summary.json', audit)
    completed = {'stage': 'student_training', 'stage_signature': signature, 'status': 'completed',
                 'best_adapter': str(best_dir), 'adapter_sha256': adapter_sha, 'attempt_directory': str(attempt),
                 'best_epoch': best_epoch, 'best_patient11_validation_ba': best_ba,
                 'source_adapter_sha256': prepared['source']['completed']['adapter_sha256'],
                 'teacher_unchanged': teacher is None or adapter_tensor_hash(teacher) == teacher_initial}
    save_json(stage_dir / 'completed.json', completed)
    print('SELECTED STUDENT ADAPTER:', best_dir)
    return completed


def run_continual_experiment(prepared):
    student = teacher = processor = None
    started = time.perf_counter()
    try:
        student, processor, dtype = build_from_old_checkpoint(prepared, 'student')
        if METHOD == 'replay_kd':
            teacher, teacher_processor, teacher_dtype = build_from_old_checkpoint(prepared, 'teacher')
            if teacher_dtype != dtype or teacher_processor.tokenizer.get_vocab() != processor.tokenizer.get_vocab():
                raise RuntimeError('Teacher/student precision or vocabulary differs.')
            del teacher_processor
        save_json(prepared['run_dir'] / 'runtime_environment.json', {
            'source_versions': prepared['source']['setup'].get('versions'),
            'base_commit': prepared['source']['setup']['base_commit'],
            'base_revision_resolution': prepared['source']['setup']['base_revision_resolution'],
            'current_versions': {'python': sys.version, 'torch': torch.__version__, 'transformers': transformers.__version__,
                                 'peft': peft.__version__, 'bitsandbytes': bnb.__version__},
            'gpu': torch.cuda.get_device_name(0), 'dtype': str(dtype)})
        smoke_check(student, teacher, processor, dtype, prepared)
        trained = train_continual_student(student, teacher, processor, dtype, prepared)
        teacher = None
        gc.collect()
        torch.cuda.empty_cache()
        student.gradient_checkpointing_disable()
        set_training_cache(student, True)
        # Only after student selection do we run the four held-out test sets.
        load_adapter_exact(student, prepared['initial_adapter'])
        before = evaluate_all(student, processor, dtype, prepared, prepared['initial_adapter'], 'before')
        load_adapter_exact(student, trained['best_adapter'])
        after = evaluate_all(student, processor, dtype, prepared, trained['best_adapter'], 'after')
        comparison, finding = compare_results(before, after, prepared['run_dir'])
        if file_sha256(adapter_file(prepared['source']['completed']['best_adapter'])) != prepared['source']['completed']['adapter_sha256']:
            raise RuntimeError('Original old-patient adapter changed on disk.')
        result = {'method': METHOD, 'source_checkpoint': prepared['source']['completed'], 'student': trained,
                  'before_directory': str(before['directory']), 'after_directory': str(after['directory']),
                  'summary': finding, 'wall_seconds': time.perf_counter() - started}
        save_json(prepared['run_dir'] / 'experiment_completed.json', result)
        return result
    finally:
        student = teacher = processor = None
        gc.collect()
        torch.cuda.empty_cache()

