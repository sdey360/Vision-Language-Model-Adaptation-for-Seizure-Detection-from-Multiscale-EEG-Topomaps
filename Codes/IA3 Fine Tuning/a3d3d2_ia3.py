def move_batch_to_device(batch: Dict[str, torch.Tensor]) -> Dict[str, torch.Tensor]:

    moved = {}

    for k, v in batch.items():

        if isinstance(v, torch.Tensor):

            if torch.is_floating_point(v):

                moved[k] = v.to(DEVICE, dtype=DTYPE, non_blocking=True)

            else:

                moved[k] = v.to(DEVICE, non_blocking=True)

        else:

            moved[k] = v

    return moved





def build_prompt_inputs(image: Image.Image) -> Dict[str, torch.Tensor]:

    inputs = processor.apply_chat_template(

        make_prompt_messages(image),

        add_generation_prompt=True,

        tokenize=True,

        return_dict=True,

        return_tensors="pt",

    )

    return dict(inputs)





def build_supervised_inputs(image: Image.Image, answer_text: str) -> Dict[str, torch.Tensor]:

    full_inputs = processor.apply_chat_template(

        make_supervised_messages(image, answer_text),

        add_generation_prompt=False,

        tokenize=True,

        return_dict=True,

        return_tensors="pt",

    )



    prompt_inputs = processor.apply_chat_template(

        make_prompt_messages(image),

        add_generation_prompt=True,

        tokenize=True,

        return_dict=True,

        return_tensors="pt",

    )



    full_inputs = dict(full_inputs)

    labels = full_inputs["input_ids"].clone()

    prompt_len = prompt_inputs["input_ids"].shape[-1]

    labels[:, :prompt_len] = -100



    if "attention_mask" in full_inputs:

        labels[full_inputs["attention_mask"] == 0] = -100



    full_inputs["labels"] = labels

    return full_inputs







