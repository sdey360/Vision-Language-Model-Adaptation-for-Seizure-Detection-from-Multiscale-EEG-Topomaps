def find_column(df: pd.DataFrame, candidates: List[str], required: bool, kind: str) -> Optional[str]:

    lower_to_real = {str(c).strip().lower(): c for c in df.columns}

    for cand in candidates:

        if cand.lower() in lower_to_real:

            return lower_to_real[cand.lower()]



    for c in df.columns:

        c_low = str(c).strip().lower()

        if kind == "image" and ("image" in c_low or "filename" in c_low or c_low.endswith("path")):

            return c

        if kind == "label" and ("label" in c_low or "class" in c_low or "target" in c_low):

            return c



    if required:

        raise ValueError(f"Could not find a {kind} column. Available columns:\n{list(df.columns)}")

    return None





def label_to_id(value) -> int:

    if pd.isna(value):

        raise ValueError("Missing label")



    if isinstance(value, (int, np.integer)) and int(value) in (0, 1):

        return int(value)

    if isinstance(value, (float, np.floating)) and not math.isnan(float(value)):

        if int(value) in (0, 1) and float(value) == int(value):

            return int(value)



    text = str(value).strip().lower().replace("_", "-")

    text_compact = re.sub(r"[\s\-]+", "", text)



    if text in {"0", "0.0", "false", "normal", "non seizure", "non-seizure", "nonseizure"}:

        return 0

    if text in {"1", "1.0", "true", "ictal", "seizure"}:

        return 1

    if "non" in text_compact and "seiz" in text_compact:

        return 0

    if "seiz" in text_compact or "ictal" in text_compact:

        return 1



    raise ValueError(f"Cannot convert label value to 0/1: {value!r}")





def join_cross_platform(root: str, suffix: str) -> str:

    parts = [p for p in re.split(r"[\\\\/]+", suffix) if p]

    return str(Path(root).joinpath(*parts))





def apply_root_remap(raw_path: str) -> str:

    normalized_raw = raw_path.replace("/", "\\\\")

    for old_root, new_root in IMAGE_ROOT_REMAPS.items():

        old_norm = old_root.replace("/", "\\\\").rstrip("\\\\")

        if normalized_raw.lower().startswith(old_norm.lower()):

            suffix = normalized_raw[len(old_norm) :].lstrip("\\\\/")

            first_candidate = join_cross_platform(new_root, suffix)

            if Path(first_candidate).exists():

                return first_candidate

            for drive_root in DRIVE_ROOT_CANDIDATES:

                candidate = join_cross_platform(str(drive_root), suffix)

                if Path(candidate).exists():

                    return candidate

            return first_candidate

    return raw_path





def build_filename_index(root: Path) -> Dict[str, str]:

    key = str(root.resolve()) if root.exists() else str(root)

    if key in _filename_search_cache:

        return _filename_search_cache[key]



    index: Dict[str, str] = {}

    if root.exists():

        for ext in ("*.png", "*.jpg", "*.jpeg", "*.bmp", "*.webp"):

            for p in root.rglob(ext):

                index.setdefault(p.name.lower(), str(p))



    _filename_search_cache[key] = index

    return index





