    p = Path(raw)



    if p.exists():

        return str(p)



    csv_parent = csv_path.parent

    candidate = csv_parent / raw

    if candidate.exists():

        return str(candidate)



    # If the CSV was downloaded to /content but contains a path relative to the

    # original Drive root, try the known Drive roots before falling back to a

    # filename search.

    relative_raw = raw.replace("\\\\", "/").lstrip("/")

    for drive_root in DRIVE_ROOT_CANDIDATES:

        candidate = drive_root / relative_raw

        if candidate.exists():

            return str(candidate)



    filename = Path(raw.replace("\\\\", "/")).name

    if filename:

        index = build_filename_index(csv_parent)

        found = index.get(filename.lower())

        if found:

            return found



        for search_root in IMAGE_SEARCH_ROOTS:

            if not Path(search_root).exists():

                continue

            index = build_filename_index(Path(search_root))

            found = index.get(filename.lower())

            if found:

                return found



    return raw





