def find_ia3_target_modules(model) -> Tuple[List[str], List[str]]:

    target_modules = []

    feedforward_modules = []



    for module_name, module in model.named_modules():

        if not isinstance(module, torch.nn.Linear):

            continue



        lower_name = module_name.lower()

        if any(excluded in lower_name for excluded in EXCLUDE_MODULE_KEYWORDS):

            continue

        if not any(key in lower_name for key in LANGUAGE_MODULE_KEYWORDS):

            continue

        if not module_name.endswith(IA3_SUFFIXES):

            continue



        target_modules.append(module_name)

        if module_name.endswith(IA3_FEEDFORWARD_SUFFIXES):

            feedforward_modules.append(module_name)



    if not target_modules:

        raise RuntimeError(

            "No IA3 target modules were found. Print model.named_modules() and update "

            "LANGUAGE_MODULE_KEYWORDS / IA3_SUFFIXES for this Transformers version."

        )

    if not feedforward_modules:

        raise RuntimeError("No IA3 feedforward modules were found.")



    return target_modules, feedforward_modules





