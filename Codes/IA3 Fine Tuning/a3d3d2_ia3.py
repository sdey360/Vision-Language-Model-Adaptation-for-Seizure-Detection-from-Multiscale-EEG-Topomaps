    print(f"Specificity:  {metrics['specificity_recall_nonseizure'] * 100:.2f}%")

    print(f"Precision:    {metrics['precision_seizure'] * 100:.2f}%")

    print(f"F1:           {metrics['f1_seizure']:.4f}")

    print(f"CM [[TN, FP], [FN, TP]] = [[{metrics['tn']}, {metrics['fp']}], [{metrics['fn']}, {metrics['tp']}]]")







