def find_column(df: pd.DataFrame, candidates: List[str], required: bool, kind: str) -> Optional[str]:
    lower_to_real = {canonical_column_name(c): c for c in df.columns}
    for cand in candidates:
        if canonical_column_name(cand) in lower_to_real:
            return lower_to_real[canonical_column_name(cand)]
    for c in df.columns:
        c_low = str(c).strip().lower()
        if kind == "image" and ("image" in c_low or "filename" in c_low or c_low.endswith("path")):
            return c
        if kind == "label" and ("label" in c_low or "class" in c_low or "target" in c_low):
            return c
    if required:
        raise ValueError(f"Could not find a {kind} column. Available columns:\n{list(df.columns)}")
    return None
def label_to_id(value) -> int:
    if pd.isna(value):
        raise ValueError("Missing label")
    if isinstance(value, (int, np.integer)) and int(value) in (0, 1):
        return int(value)
    if isinstance(value, (float, np.floating)) and not math.isnan(float(value)):
        if int(value) in (0, 1) and float(value) == int(value):
            return int(value)
    text = str(value).strip().lower().replace("_", "-")
    text_compact = re.sub(r"[\s\-]+", "", text)
    if text in {"0", "0.0", "false", "normal", "non seizure", "non-seizure", "nonseizure"}:
        return 0
    if text in {"1", "1.0", "true", "ictal", "seizure"}:
        return 1
    if "non" in text_compact and "seiz" in text_compact:
        return 0
    if "seiz" in text_compact or "ictal" in text_compact:
        return 1
    raise ValueError(f"Cannot convert label value to 0/1: {value!r}")
