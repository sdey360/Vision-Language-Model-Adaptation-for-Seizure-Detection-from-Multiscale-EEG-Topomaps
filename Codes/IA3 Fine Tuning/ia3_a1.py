def canonical_column_name(value):
    # Accept Label, True Label, true_label, and true-label consistently.
    return re.sub(r"[^a-z0-9]", "", str(value).strip().lower().lstrip("\ufeff"))

def read_metadata_csv(path, **kwargs):
    frame = pd.read_csv(path, **kwargs)
    if len(frame.columns) == 1:
        # Excel exports can use semicolons or tabs instead of commas.
        alternate = pd.read_csv(path, sep=None, engine="python", **kwargs)
        if len(alternate.columns) > 1:
            frame = alternate
    return frame

def has_a1_marker(path):
    # Match A1 as a complete marker; do not confuse it with A10 or Patient 11.
    return re.search(
        r"(?<![a-z0-9])a1(?!\d)(?=$|[^a-z0-9]|training|traininng|testing|test|fine|topomap|blind|variance|coeff)",
        str(path).lower(),
    ) is not None

def path_patient_ids(path):
    normalized = str(path).replace("\\", "/").lower()
    return {str(int(x)).zfill(2) for x in re.findall(r"pati?ient[ _-]*0*(\d+)(?!\d)", normalized)}

def csv_has_image_and_label(csv_path):
    return csv_schema_problem(csv_path) is None

def csv_schema_problem(csv_path):
    try:
        columns = list(read_metadata_csv(csv_path, nrows=0).columns)
        normalized = {canonical_column_name(column) for column in columns}
    except Exception as error:
        return f"CSV could not be read: {error}"
    if normalized & {"predlabel", "predictedlabel", "prediction", "rawgeneration"}:
        return "prediction output, rather than source test metadata"
    if not normalized & {canonical_column_name(x) for x in _CSV_IMAGE_COLUMNS}:
        return f"no recognized image column; columns={columns}"
    if not normalized & {canonical_column_name(x) for x in _CSV_LABEL_COLUMNS}:
        return f"no recognized true-label column; columns={columns}"
    return None

def scan_csv_files(roots):
    found = set()
    for root in roots:
        if not root.is_dir():
            continue
        for directory, folders, files in os.walk(root):
            folders[:] = [folder for folder in folders if not folder.startswith(".") and "medgemma" not in folder.lower()]
            for filename in files:
                if filename.lower().endswith(".csv"):
                    found.add(Path(directory) / filename)
    return sorted(found)

def candidate_paths(*parts):
    return [root.joinpath(*parts) for root in DRIVE_ROOT_CANDIDATES]

def discover_csv(kind, candidates, manual_path="", patient_id=None):
    global _drive_csv_inventory, _drive_csv_inventory_expanded
    title = "pooled A1 training" if kind == "train" else f"Patient {patient_id} A1 blinded test"
    if manual_path:
        selected = Path(manual_path)
        if not selected.is_file():
            raise FileNotFoundError(f"{title} CSV override does not exist: {selected}")
        problem = csv_schema_problem(selected)
        if problem:
            raise ValueError(f"Invalid {title} CSV override: {selected}\n{problem}")
        ids = path_patient_ids(selected)
        if patient_id and ids and ids != {patient_id}:
            raise ValueError(f"Patient mismatch for {title}: {selected}")
        print(f"{title} CSV (manual): {selected}")
        return str(selected)
    for selected in dict.fromkeys(candidates):
        if selected.is_file() and csv_has_image_and_label(selected):
            print(f"{title} CSV: {selected}")
            return str(selected)
    if _drive_csv_inventory is None:
        print("Searching Google Drive for A1 metadata CSVs...")
        roots = [p for p in DRIVE_ROOT_CANDIDATES if p.is_dir()] or [DRIVE_MYDRIVE]
        _drive_csv_inventory = scan_csv_files(roots)
    def eligible_candidates():
        accepted, rejected = [], []
        for path in _drive_csv_inventory:
            low = str(path).lower()
            name = path.name.lower()
            if not has_a1_marker(path):
                continue
            if any(x in low for x in ["medgemma", "patient_evaluations", "test_predictions", "training_history"]):
                continue
            ids = path_patient_ids(path)
            if kind == "train":
                if ids or not any(x in low for x in ["training", "traininng"]):
                    continue
                if "test" in name or "blind" in name or "prediction" in name:
                    continue
            else:
                if ids != {patient_id}:
                    continue
                # Ground-truth labels may live in blinded_metadata.csv, or a
                # separate labels CSV beside the blinded images. Inspect the schema.
                if not any(x in low for x in ["blind", "testing", "test", "label"]):
                    continue
            problem = csv_schema_problem(path)
            if problem:
                rejected.append((path, problem))
            else:
                accepted.append(path)
        return accepted, rejected
    found, rejected = eligible_candidates()
    if not found and not _drive_csv_inventory_expanded:
        print(f"No valid {title} CSV in the preferred folders; expanding search to MyDrive...")
        _drive_csv_inventory = sorted(set(_drive_csv_inventory) | set(scan_csv_files([DRIVE_MYDRIVE])))
        _drive_csv_inventory_expanded = True
        found, rejected = eligible_candidates()
    # Prefer the original true-label CSV to a metadata sidecar or copied file.
    # Never choose arbitrarily between equally preferred dataset splits.
    def preference(path):
        name = path.name.lower()
        return (int(name.startswith("copy of ")), 0 if "label" in name else 1)
    preferred = []
    if found:
        best_preference = min(preference(path) for path in found)
        preferred = [path for path in found if preference(path) == best_preference]
    if len(preferred) != 1:
        for path in found:
            print("  Valid candidate:", path)
        for path, reason in rejected[:20]:
            print(f"  Rejected candidate: {path}\n    Reason: {reason}")
        setting = "MANUAL_TRAIN_CSV" if kind == "train" else f'MANUAL_TEST_CSVS["{patient_id}"]'
        raise FileNotFoundError(
            f"Found {len(found)} valid candidates ({len(preferred)} equally preferred) for {title}. "
            f"Set {setting} to the exact mounted Google Drive CSV path. "
            "If none were listed, ensure its CSV and A1 image folder are uploaded and available in MyDrive."
        )
    selected = preferred[0]
    print(f"{title} CSV (discovered): {selected}")
    print("Columns:", list(read_metadata_csv(selected, nrows=0).columns))
    return str(selected)

