for epoch in range(1, NUM_EPOCHS + 1):
    print("\n" + "=" * 100)
    print(f"EPOCH {epoch}/{NUM_EPOCHS}")
    print("=" * 100)

    model.train()
    epoch_losses = []
    epoch_start_time = time.time()
    epoch_parameter_snapshot = snapshot_trainable_parameters()

    optimizer.zero_grad(set_to_none=True)

    progress = tqdm(
        enumerate(train_loader, start=1),
        total=len(train_loader),
        desc=f"LoReFT R4 training epoch {epoch}",
    )

    accumulation_count = 0

    for batch_number, batch in progress:
        try:
            batch = move_batch_to_device(batch)

            with autocast_context():
                outputs = model(**batch)
                raw_loss = outputs.loss
                scaled_loss = raw_loss / GRADIENT_ACCUMULATION_STEPS

            if not torch.isfinite(raw_loss):
                raise RuntimeError("Training loss became NaN/Inf.")

            if grad_scaler is not None:
                grad_scaler.scale(scaled_loss).backward()
            else:
                scaled_loss.backward()

            accumulation_count += 1
            current_loss = float(raw_loss.detach().float().cpu())
            epoch_losses.append(current_loss)

            should_update = accumulation_count == GRADIENT_ACCUMULATION_STEPS or batch_number == len(train_loader)

            if should_update:
                if grad_scaler is not None:
                    grad_scaler.unscale_(optimizer)

                gradient_l2, grad_tensor_count, nonzero_grad_tensors = trainable_gradient_l2_norm()
                optimizer_lr_before_step = float(optimizer.param_groups[0]["lr"])
                diagnostic_this_step = False

                if not first_nonzero_lr_update_checked and optimizer_lr_before_step > 0.0:
                    diagnostic_this_step = True
                    first_update_before = snapshot_trainable_parameters()

                    print("\n" + "=" * 100)
                    print("FIRST NON-ZERO-LR LoReFT UPDATE DIAGNOSTIC")
                    print("=" * 100)
                    print(f"Optimizer LR before step     : {optimizer_lr_before_step:.12e}")
                    print(f"Gradient L2 norm before clip : {gradient_l2:.12e}")
                    print(f"Gradient tensors present     : {grad_tensor_count}")
                    print(f"Gradient tensors non-zero    : {nonzero_grad_tensors}")

                    if grad_tensor_count == 0 or nonzero_grad_tensors == 0 or gradient_l2 <= 0.0:
                        raise RuntimeError("LoReFT received no non-zero gradient on the first non-zero-LR update.")

                elif (
                    not first_nonzero_lr_update_checked
                    and optimizer_lr_before_step == 0.0
                    and not zero_lr_warmup_step_reported
                ):
                    print("\n" + "=" * 100)
                    print("LoReFT WARMUP NOTE")
                    print("=" * 100)
                    print("Optimizer LR before step     : 0.000000000000e+00")
                    print(f"Gradient L2 norm before clip : {gradient_l2:.12e}")
                    print(f"Gradient tensors present     : {grad_tensor_count}")
                    print(f"Gradient tensors non-zero    : {nonzero_grad_tensors}")
                    print("The first optimizer step can use LR=0 because of linear warmup.")
                    print("=" * 100)
                    zero_lr_warmup_step_reported = True

                clipped_norm = torch.nn.utils.clip_grad_norm_(trainable_parameters, MAX_GRAD_NORM)

                if grad_scaler is not None:
                    grad_scaler.step(optimizer)
                    grad_scaler.update()
                else:
                    optimizer.step()

                scheduler.step()

                if diagnostic_this_step:
                    first_delta_l2, first_delta_max = parameter_change_from_snapshot(first_update_before)
                    print(f"Gradient norm returned by clip: {float(clipped_norm):.12e}")
                    print(f"Parameter delta L2           : {first_delta_l2:.12e}")
                    print(f"Parameter delta max abs      : {first_delta_max:.12e}")

                    if first_delta_l2 <= 0.0 or first_delta_max <= 0.0:
                        raise RuntimeError("LoReFT parameters did not change on the first optimizer step with LR > 0.")

                    print("SUCCESS: LoReFT parameters changed on the first non-zero-LR optimizer step.")
                    print("=" * 100)
                    print_effective_rotation_norms("POST-FIRST-NONZERO-LR EFFECTIVE ROTATION-NORM CHECK")
                    first_nonzero_lr_update_checked = True

                optimizer.zero_grad(set_to_none=True)
                accumulation_count = 0

            current_lr = scheduler.get_last_lr()[0]
            gpu_gb = torch.cuda.memory_allocated() / 1024**3
            progress.set_postfix(loss=f"{current_loss:.4f}", lr=f"{current_lr:.2e}", gpu=f"{gpu_gb:.2f}GB")

            del batch
            del outputs
            del raw_loss
            del scaled_loss

        except torch.cuda.OutOfMemoryError as error:
            torch.cuda.empty_cache()
            raise RuntimeError(
                "\nCUDA OUT OF MEMORY DURING LoReFT R4.\n"
                "Do not switch this run to 4-bit, because that would make it a QLoRA experiment."
            ) from error

    mean_training_loss = float(np.mean(epoch_losses))
    epoch_parameter_delta_l2, epoch_parameter_delta_max = parameter_change_from_snapshot(epoch_parameter_snapshot)

    print("\nLoReFT epoch parameter change:")
    print(f"  L2 delta      : {epoch_parameter_delta_l2:.12e}")
    print(f"  Max abs delta : {epoch_parameter_delta_max:.12e}")

    if epoch_parameter_delta_l2 <= 0.0 or epoch_parameter_delta_max <= 0.0:
        raise RuntimeError(f"LoReFT parameters did not change during epoch {epoch}.")

    print_effective_rotation_norms(f"EPOCH {epoch} EFFECTIVE LoReFT ROTATION-NORM CHECK")

