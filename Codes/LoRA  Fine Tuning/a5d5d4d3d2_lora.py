def resolve_case_insensitive(path):
    path = Path(path)

    if path.exists():
        return path

    if path.is_absolute():
        current = Path(path.anchor)
        parts = path.parts[1:]
    else:
        current = Path(".")
        parts = path.parts

    for part in parts:
        direct = current / part
        if direct.exists():
            current = direct
            continue

        if current.exists() and current.is_dir():
            matches = [
                child for child in current.iterdir()
                if child.name.lower() == part.lower()
            ]
            if matches:
                current = matches[0]
                continue

        current = direct

    return current

def first_existing(paths):
    for path in paths:
        real_path = resolve_case_insensitive(path)
        if real_path.exists():
            return real_path
    return resolve_case_insensitive(paths[0])

