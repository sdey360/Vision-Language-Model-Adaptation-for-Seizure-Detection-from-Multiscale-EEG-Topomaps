        early_stop_epoch = epoch

        print("\n" + "=" * 100)
        print("EARLY STOPPING TRIGGERED")
        print("=" * 100)
        print(f"\nNo new best checkpoint for {EARLY_STOPPING_PATIENCE} consecutive epochs.")
        print(f"Stopping at epoch     : {early_stop_epoch}")
        print(f"Best epoch            : {best_epoch}")
        print(f"Best validation BA    : {best_validation_balanced_accuracy:.4f}")
        print(f"Best validation loss  : {best_validation_loss:.6f}")
        print("Final blinded tests will use the BEST saved checkpoint.")
        break


