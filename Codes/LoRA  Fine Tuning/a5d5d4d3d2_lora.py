def resolve_image_path(csv_path, value):
    if pd.isna(value) or not str(value).strip():
        raise ValueError(f"Missing image path in {csv_path}")

    raw_value = str(value).strip().strip('"').strip("'")
    image_path = Path(raw_value)

    if image_path.is_absolute():
        image_path = resolve_case_insensitive(image_path)
    else:
        image_path = resolve_case_insensitive(csv_path.parent / image_path)

    if image_path.is_file():
        return image_path

    filename_only = Path(raw_value.replace("\\", "/")).name
    direct_filename = resolve_case_insensitive(csv_path.parent / filename_only)

    if direct_filename.is_file():
        return direct_filename

    search_roots = [csv_path.parent]

    if csv_path.parent.name.lower() in {"blinded", "blind"}:
        search_roots.append(csv_path.parent.parent)

    matches = []

    for root in search_roots:
        if root.exists() and root.is_dir():
            matches.extend(root.rglob(filename_only))

    if not matches:
        target_lower = filename_only.lower()
        for root in search_roots:
            if root.exists() and root.is_dir():
                for candidate in root.rglob("*"):
                    if candidate.is_file() and candidate.name.lower() == target_lower:
                        matches.append(candidate)

    unique_matches = []
    seen = set()

    for match in matches:
        key = str(match.resolve()).lower()
        if key not in seen:
            seen.add(key)
            unique_matches.append(match)

    if len(unique_matches) == 1:
        return unique_matches[0]

    if len(unique_matches) > 1:
        raise FileNotFoundError(
            f"Multiple images named {filename_only!r} were found under:\n"
            f"{csv_path.parent}\nUse an absolute image_path column or set COLUMN_OVERRIDES."
        )

    raise FileNotFoundError(
        f"Image not found:\n{image_path}\nSource CSV:\n{csv_path}"
    )

def load_metadata(csv_path, dataset_name):
    csv_path = resolve_case_insensitive(csv_path)

    if not csv_path.is_file():
        raise FileNotFoundError(f"{dataset_name}: CSV not found:\n{csv_path}")

    df = pd.read_csv(csv_path)

    if df.empty:
        raise ValueError(f"{dataset_name}: empty CSV:\n{csv_path}")

    df.columns = [str(column).strip() for column in df.columns]

    override = COLUMN_OVERRIDES.get(dataset_name, {})
    df = attach_labels_from_companion(df, csv_path, dataset_name)

    image_column = pick_column(
        df,
        BLIND_PATH_COLUMN_CANDIDATES if dataset_name != "pooled" else PATH_COLUMN_CANDIDATES,
        override.get("path"),
    )

    label_column = override.get("label") or find_label_column(df)

    if label_column is None:
        raise ValueError(
            f"{dataset_name}: no label column found. Available columns:\n{list(df.columns)}"
        )

    labels = df[label_column].map(normalize_label).astype(int)

    resolved_paths = []
    pixel_hashes = []

    for value in tqdm(df[image_column], desc=f"Validate images: {dataset_name}"):
        image_path = resolve_image_path(csv_path, value)

        with Image.open(image_path) as source:
            rgb = source.convert("RGB")
            pixel_hash = hashlib.sha256(
                str(rgb.size).encode() + rgb.tobytes()
            ).hexdigest()

        resolved_paths.append(str(image_path.resolve()))
        pixel_hashes.append(pixel_hash)

    df = df.copy()
    df["image_path"] = resolved_paths
    df["label"] = labels
    df["class_name"] = df["label"].map({0: "non_seizure", 1: "seizure"})
    df["pixel_sha256"] = pixel_hashes
    df["metadata_source"] = str(csv_path)

    if set(df["label"]) != {0, 1}:
        raise ValueError(f"{dataset_name} must contain both classes.")

    print(
        f"\n{dataset_name}: {len(df)} images"
        f"\nClass counts: {df['label'].value_counts().to_dict()}"
        f"\nCSV: {csv_path}"
    )

    return df

def verify_no_duplicates(pool, tests, output):
    frames = [pool.assign(dataset="pooled")]
    frames += [df.assign(dataset=f"test_{patient}") for patient, df in tests.items()]

    combined = pd.concat(frames, ignore_index=True)
    repeated = combined[combined.duplicated("pixel_sha256", keep=False)]

    if not repeated.empty:
        report = output / "duplicate_image_report.csv"
        repeated.to_csv(report, index=False)

        raise ValueError(
            "Identical image pixels were found within/across datasets.\n"
            f"Inspect:\n{report}"
        )

def split_pool(pool):
    training_parts = []
    validation_parts = []

    for label in (0, 1):
        group = pool[pool["label"] == label].sample(frac=1, random_state=SEED)

        if len(group) < 2:
            raise ValueError("Need at least two pooled examples per class.")

        validation_count = max(
            1,
            min(len(group) - 1, math.ceil(len(group) * VAL_FRACTION)),
        )

        validation_parts.append(group.iloc[-validation_count:])
        training_parts.append(group.iloc[:-validation_count])

    training_df = (
        pd.concat(training_parts)
        .sample(frac=1, random_state=SEED)
        .reset_index(drop=True)
    )

    validation_df = (
        pd.concat(validation_parts)
        .sample(frac=1, random_state=SEED)
        .reset_index(drop=True)
    )

    return training_df, validation_df

