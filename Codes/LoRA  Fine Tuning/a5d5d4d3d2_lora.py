def move(batch, dtype):
    return {
        key: (
            value.to(
                "cuda:0",
                dtype=(dtype if value.is_floating_point() else value.dtype),
            )
            if torch.is_tensor(value)
            else value
        )
        for key, value in batch.items()
    }

def load_base(dtype):
    model_class = getattr(transformers, "AutoModelForImageTextToText", None)

    if model_class is None:
        model_class = getattr(transformers, "AutoModelForMultimodalLM", None)

    if model_class is None:
        raise RuntimeError(
            "Transformers does not have AutoModelForImageTextToText or AutoModelForMultimodalLM. "
            "Upgrade transformers."
        )

    kwargs = dict(
        pretrained_model_name_or_path=MODEL_ID,
        torch_dtype=dtype,
        token=HF_TOKEN,
        low_cpu_mem_usage=True,
        attn_implementation="sdpa",
    )

    try:
        model = model_class.from_pretrained(**kwargs)
    except TypeError:
        kwargs.pop("attn_implementation", None)
        model = model_class.from_pretrained(**kwargs)

    return model.to("cuda:0")

def prediction_label(text):
    normalized = re.sub(
        r"[\s_\-]+",
        "",
        text.strip().lower().strip(". !\n\t"),
    )

    return {"seizure": 1, "nonseizure": 0}.get(normalized)

def decode_output(processor, token_ids):
    if hasattr(processor, "decode"):
        return processor.decode(token_ids, skip_special_tokens=True)

    return processor.tokenizer.decode(token_ids, skip_special_tokens=True)

@torch.no_grad()
def evaluate(model, processor, df, dtype, description):
    model.eval()

    raw_outputs = []
    predictions = []

    for row in tqdm(df.to_dict("records"), desc=description):
        with Image.open(row["image_path"]) as opened:
            inputs = processor.apply_chat_template(
                messages(opened.convert("RGB")),
                add_generation_prompt=True,
                tokenize=True,
                return_dict=True,
                return_tensors="pt",
            )

        prompt_length = inputs["input_ids"].shape[1]

        with torch.autocast("cuda", dtype=dtype):
            generated = model.generate(
                **move(inputs, dtype),
                max_new_tokens=MAX_NEW_TOKENS,
                do_sample=False,
                num_beams=1,
                use_cache=True,
            )

        text = decode_output(
            processor,
            generated[0, prompt_length:],
        ).strip()

        raw_outputs.append(text)
        predictions.append(prediction_label(text))

    true_labels = df["label"].to_numpy(dtype=int)

    scored_predictions = np.array(
        [
            1 - int(truth) if prediction is None else prediction
            for truth, prediction in zip(true_labels, predictions)
        ]
    )

    tn, fp, fn, tp = confusion_matrix(
        true_labels,
        scored_predictions,
        labels=[0, 1],
    ).ravel()

    metrics = {
        "n_images": len(df),
        "accuracy": float(accuracy_score(true_labels, scored_predictions)),
        "balanced_accuracy": float(balanced_accuracy_score(true_labels, scored_predictions)),
        "sensitivity": safe_divide(tp, tp + fn),
        "specificity": safe_divide(tn, tn + fp),
        "precision": float(precision_score(true_labels, scored_predictions, zero_division=0)),
        "f1": float(f1_score(true_labels, scored_predictions, zero_division=0)),
        "TN": int(tn),
        "FP": int(fp),
        "FN": int(fn),
        "TP": int(tp),
        "invalid_predictions": sum(prediction is None for prediction in predictions),
        "invalid_output_policy": "count_as_wrong_for_metrics_only",
    }

    result = df.copy()
    result["raw_output"] = raw_outputs
    result["predicted_label"] = pd.array(predictions, dtype="Int64")
    result["invalid_output"] = [prediction is None for prediction in predictions]
    result["metric_label_invalid_counted_wrong"] = scored_predictions
    result["correct"] = [
        prediction is not None and prediction == truth
        for prediction, truth in zip(predictions, true_labels)
    ]

    return metrics, result

@torch.no_grad()
def validation_loss(model, loader, dtype):
    model.eval()
    total_loss = 0.0

    for batch in tqdm(loader, desc="Validation loss"):
        with torch.autocast("cuda", dtype=dtype):
            loss = model(**move(batch, dtype)).loss

        if not torch.isfinite(loss):
            raise RuntimeError("Nonfinite validation loss.")

        total_loss += loss.item()

    return total_loss / len(loader)

