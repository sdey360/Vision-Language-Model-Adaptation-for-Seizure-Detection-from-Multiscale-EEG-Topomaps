def csv_score(csv_path, dataset_name):
    try:
        df = pd.read_csv(csv_path, nrows=50)
    except Exception:
        return -1

    df.columns = [str(column).strip() for column in df.columns]

    path_col = find_path_column(df, dataset_name)
    label_col = find_label_column(df)

    text = str(csv_path).lower()
    name = csv_path.name.lower()

    score = 0

    if path_col is not None:
        score += 100

    if label_col is not None:
        score += 50

    if "blind" in text or "blinded" in text:
        score += 50

    if "test" in text or "testing" in text:
        score += 40

    if "label" in name or "labels" in name:
        score += 25

    if "metadata" in name:
        score += 15

    if REPRESENTATION.lower() in text:
        score += 10

    if dataset_name in text or str(int(dataset_name)) in text if dataset_name.isdigit() else False:
        score += 5

    if "prediction" in text or "actual_train" in text or "validation" in text or "history" in text:
        score -= 100

    return score

