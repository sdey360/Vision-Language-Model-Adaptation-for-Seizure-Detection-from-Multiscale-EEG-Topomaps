def normalize_prediction_text(output_text):
    text = str(output_text).strip().lower()
    text = text.replace("_", " ").replace("–", "-")
    text = re.sub(r"\s+", " ", text)

    if re.search(r"\bnon[\s-]*seizure\b", text):
        return 0
    if re.search(r"\bseizure\b", text):
        return 1
    return None


