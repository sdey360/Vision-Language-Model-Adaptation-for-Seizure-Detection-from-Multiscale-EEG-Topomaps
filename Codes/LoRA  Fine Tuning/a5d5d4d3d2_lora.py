def companion_label_files(csv_path):
    folder = csv_path.parent
    stem = csv_path.stem

    candidates = []

    replacements = [
        ("_blinded_test", "_blinded_labels"),
        ("_blind_test", "_blind_labels"),
        ("_test", "_labels"),
        ("_test", "_metadata"),
    ]

    for old, new in replacements:
        if old in stem:
            candidates.append(folder / f"{stem.replace(old, new)}.csv")

    parent = folder.parent if folder.name.lower() in {"blinded", "blind"} else folder

    candidates.extend(sorted(folder.glob("*labels*.csv")))
    candidates.extend(sorted(folder.glob("*metadata*.csv")))
    candidates.extend(sorted(parent.glob("*labels*.csv")))
    candidates.extend(sorted(parent.glob("*metadata*.csv")))

    unique = []
    seen = set()

    for candidate in candidates:
        if candidate == csv_path:
            continue

        key = str(candidate.resolve()).lower()
        if key not in seen and candidate.exists():
            seen.add(key)
            unique.append(candidate)

    return unique

def normalize_global_serial_for_join(value):
    if pd.isna(value):
        return None

    text = str(value).strip()
    match = re.search(r"G\s*0*(\d+)", text, flags=re.IGNORECASE)

    if match:
        return f"G{int(match.group(1)):08d}"

    match = re.fullmatch(r"\d+", text)

    if match:
        return f"G{int(text):08d}"

    return None

def normalize_join_value(value, column_name):
    if pd.isna(value):
        return None

    text = str(value).strip().strip('"').strip("'")

    if not text:
        return None

    key = normalize_key(column_name)

    if "serial" in key:
        serial = normalize_global_serial_for_join(text)
        if serial is not None:
            return serial

    if re.search(r"G\s*0*\d+", text, flags=re.IGNORECASE):
        serial = normalize_global_serial_for_join(text)
        if serial is not None:
            return serial

    if any(token in key for token in ["path", "file", "filename", "image", "topomap"]):
        text = Path(text.replace("\\", "/")).name

    return normalize_key(text)

def attach_labels_from_companion(df, csv_path, dataset_name):
    if find_label_column(df) is not None:
        return df

    candidates = companion_label_files(csv_path)

    if not candidates:
        raise ValueError(
            f"{dataset_name}: no label column found in:\n{csv_path}\n"
            "If this is a blinded image CSV, place a matching labels CSV in the same folder."
        )

    for label_file in candidates:
        label_df = pd.read_csv(label_file)
        label_df.columns = [str(column).strip() for column in label_df.columns]

        label_column = find_label_column(label_df)

        if label_column is None:
            continue

        for left_name in JOIN_KEY_CANDIDATES:
            left_key = pick_column(df, [left_name], required=False)

            if left_key is None:
                continue

            left_join = df[left_key].map(lambda value: normalize_join_value(value, left_key))

            for right_name in JOIN_KEY_CANDIDATES:
                right_key = pick_column(label_df, [right_name], required=False)

                if right_key is None:
                    continue

                right = label_df[[right_key, label_column]].copy()
                right["_join_key"] = right[right_key].map(
                    lambda value: normalize_join_value(value, right_key)
                )
                right = right.dropna(subset=["_join_key", label_column])

                if right.empty:
                    continue

                grouped = right.groupby("_join_key")[label_column]
                conflict_keys = grouped.nunique(dropna=True)
                conflict_keys = conflict_keys[conflict_keys > 1]

                if not conflict_keys.empty:
                    continue

                label_map = grouped.first()
                attached = left_join.map(label_map)

                if attached.notna().all():
                    merged = df.copy()
                    merged[label_column] = attached

                    print(
                        f"{dataset_name}: attached labels from {label_file.name} "
                        f"using {left_key!r} -> {right_key!r}."
                    )

                    return merged

    raise ValueError(
        f"{dataset_name}: label companion files were found, but labels could not be matched.\n"
        f"Tried: {[str(path) for path in candidates]}"
    )

