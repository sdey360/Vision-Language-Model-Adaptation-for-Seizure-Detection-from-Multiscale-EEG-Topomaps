def label_to_target_text(label):
    if int(label) == 1:
        return "Seizure"
    return "Non-seizure"


def build_prompt_messages(image):
    return [
        {
            "role": "system",
            "content": [{"type": "text", "text": SYSTEM_PROMPT}],
        },
        {
            "role": "user",
            "content": [
                {"type": "text", "text": USER_PROMPT},
                {"type": "image", "image": image},
            ],
        },
    ]


def build_training_messages(image, target_text):
    messages = build_prompt_messages(image)
    messages.append(
        {
            "role": "assistant",
            "content": [{"type": "text", "text": target_text}],
        }
    )
    return messages


class MedGemmaTrainingCollator:
    def __init__(self, processor):
        self.processor = processor

    def __call__(self, examples):
        if len(examples) != 1:
            raise ValueError("This pipeline expects physical batch size = 1.")

        example = examples[0]
        image_path = example["image_path"]
        target_text = label_to_target_text(example["label"])

        with Image.open(image_path) as opened_image:
            image = opened_image.convert("RGB")

            prompt_messages = build_prompt_messages(image)
            prompt_inputs = self.processor.apply_chat_template(
                prompt_messages,
                add_generation_prompt=True,
                tokenize=True,
                return_dict=True,
                return_tensors="pt",
            )

            full_messages = build_training_messages(image, target_text)
            full_inputs = self.processor.apply_chat_template(
                full_messages,
                add_generation_prompt=False,
                tokenize=True,
                return_dict=True,
                return_tensors="pt",
            )

        prompt_ids = prompt_inputs["input_ids"]
        full_ids = full_inputs["input_ids"]
        prompt_length = int(prompt_ids.shape[1])

        if full_ids.shape[1] <= prompt_length:
            raise RuntimeError("Full training conversation contains no target response.")

        prefix_matches = torch.equal(full_ids[:, :prompt_length], prompt_ids)
        if not prefix_matches:
            raise RuntimeError("MedGemma chat template prefix mismatch. Training stopped.")

        labels = full_ids.clone()
        labels[:, :prompt_length] = -100

        if int((labels != -100).sum()) == 0:
            raise RuntimeError("No assistant target tokens remain after masking.")

        full_inputs["labels"] = labels
        return full_inputs


