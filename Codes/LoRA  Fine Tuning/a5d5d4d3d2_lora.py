def normalize_label_value(x):
    if pd.isna(x):
        return np.nan

    text = str(x).strip().lower()

    if text in {"0", "0.0", "non-seizure", "non seizure", "nonseizure", "normal", "ns"}:
        return 0
    if text in {"1", "1.0", "seizure", "ictal", "sz"}:
        return 1

    if "non" in text and "seizure" in text:
        return 0
    if "seizure" in text:
        return 1

    return np.nan

