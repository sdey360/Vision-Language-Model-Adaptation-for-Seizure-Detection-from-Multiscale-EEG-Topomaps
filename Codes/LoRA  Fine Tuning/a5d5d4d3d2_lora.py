class Topomaps(Dataset):
    def __init__(self, df):
        self.rows = df.to_dict("records")

    def __len__(self):
        return len(self.rows)

    def __getitem__(self, index):
        return self.rows[index]

def messages(image):
    return [
        {
            "role": "system",
            "content": [{"type": "text", "text": SYSTEM_PROMPT}],
        },
        {
            "role": "user",
            "content": [
                {"type": "text", "text": USER_PROMPT},
                {"type": "image", "image": image},
            ],
        },
    ]

class Collator:
    def __init__(self, processor):
        self.processor = processor

    def __call__(self, rows):
        if len(rows) != 1:
            raise ValueError("Physical batch size must be 1.")

        row = rows[0]

        with Image.open(row["image_path"]) as opened:
            image = opened.convert("RGB")
            chat = messages(image)

            prompt = self.processor.apply_chat_template(
                chat,
                add_generation_prompt=True,
                tokenize=True,
                return_dict=True,
                return_tensors="pt",
            )

            target_text = "Seizure" if row["label"] == 1 else "Non-seizure"

            chat.append(
                {
                    "role": "assistant",
                    "content": [{"type": "text", "text": target_text}],
                }
            )

            full = self.processor.apply_chat_template(
                chat,
                add_generation_prompt=False,
                tokenize=True,
                return_dict=True,
                return_tensors="pt",
            )

        prompt_length = prompt["input_ids"].shape[1]

        if (
            full["input_ids"].shape[1] <= prompt_length
            or not torch.equal(full["input_ids"][:, :prompt_length], prompt["input_ids"])
        ):
            raise RuntimeError("Chat-template prefix mismatch.")

        full["labels"] = full["input_ids"].clone()
        full["labels"][:, :prompt_length] = -100

        if "attention_mask" in full:
            full["labels"][full["attention_mask"] == 0] = -100

        return full

