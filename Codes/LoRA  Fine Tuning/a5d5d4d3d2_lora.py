def resolve_loreft_model_info(multimodal_model, target_layers_human):
    language_model_object, language_layers, language_layers_path = find_language_layers(multimodal_model)
    num_language_layers = len(language_layers)

    target_layers_human = [int(x) for x in target_layers_human]
    if len(target_layers_human) != len(set(target_layers_human)):
        raise ValueError("Duplicate LoReFT target layers were requested.")

    for human_layer in target_layers_human:
        if human_layer < 1 or human_layer > num_language_layers:
            raise ValueError(f"Requested LoReFT layer {human_layer}, but the language model has {num_language_layers} layers.")

    target_layer_indices = [human_layer - 1 for human_layer in target_layers_human]

    if hasattr(multimodal_model.config, "text_config") and hasattr(multimodal_model.config.text_config, "hidden_size"):
        hidden_size = int(multimodal_model.config.text_config.hidden_size)
    elif language_model_object is not None and hasattr(language_model_object, "config"):
        hidden_size = int(language_model_object.config.hidden_size)
    else:
        raise RuntimeError("Could not determine the language hidden size.")

    return {
        "language_model_object": language_model_object,
        "language_layers": language_layers,
        "language_layers_path": language_layers_path,
        "num_language_layers": num_language_layers,
        "hidden_size": hidden_size,
        "target_layers_human": target_layers_human,
        "target_layer_indices": target_layer_indices,
    }


def attach_loreft(
    base,
    target_layers_human,
    rank,
    prefix_tokens,
    suffix_tokens,
    dropout,
    trainable,
    saved_state=None,
    saved_config=None,
):
    info = resolve_loreft_model_info(base, target_layers_human)
    language_layers = info["language_layers"]
    target_layer_indices = info["target_layer_indices"]

    controller = LoReFTPositionController(prefix_tokens=prefix_tokens, suffix_tokens=suffix_tokens)
    target_language_layers = []
    interventions = {}
    hook_handles = []

    for human_layer, python_index in zip(info["target_layers_human"], target_layer_indices):
        layer_key = str(human_layer)
        target_layer = language_layers[python_index]

        intervention = LoReFTIntervention(
            embed_dim=info["hidden_size"],
            rank=rank,
            train_dtype=torch.float32,
            dropout=dropout,
        ).to(DEVICE)

        target_layer.add_module(LOREFT_MODULE_NAME, intervention)

        if saved_state is not None:
            if layer_key not in saved_state:
                raise RuntimeError(f"Missing saved LoReFT state for human layer {human_layer}.")
            intervention.load_state_dict(saved_state[layer_key], strict=True)

        for parameter in intervention.parameters():
            parameter.requires_grad = bool(trainable)

        hook_handle = target_layer.register_forward_hook(make_loreft_hook(intervention, controller))

        target_language_layers.append(target_layer)
        interventions[layer_key] = intervention
        hook_handles.append(hook_handle)

    checkpoint_info = {
        "method": "LoReFT",
        "variant": "multi_layer_independent_interventions",
        "formula": "h + R^T(Wh + b - Rh)",
        "rank": rank,
        "num_language_layers": info["num_language_layers"],
        "target_layers_human": info["target_layers_human"],
        "target_layer_python_indices": target_layer_indices,
        "num_interventions": len(target_layer_indices),
        "hidden_size": info["hidden_size"],
        "prefix_prompt_tokens": prefix_tokens,
        "suffix_prompt_tokens": suffix_tokens,
        "dropout": dropout,
        "component": LOREFT_COMPONENT,
        "language_layers_path": info["language_layers_path"],
        "precision_fix": "autocast disabled inside LoReFT; true FP32 projection + FP32 residual addition; one final cast to model dtype",
        "initialization": "identity_no_op_W_equals_R_transpose_bias_zero",
        "bf16_diagnostic": True,
        "rotation_weight_decay": 0.0,
        "source_weight_decay": WEIGHT_DECAY,
        "source_bias_weight_decay": 0.0,
    }

    if saved_config is not None:
        checkpoint_info.update(saved_config)

    wrapper = MedGemmaLoReFTWrapper(
        base=base,
        controller=controller,
        interventions=interventions,
        checkpoint_info=checkpoint_info,
    ).to(DEVICE)

    return wrapper, info, controller, interventions, hook_handles, target_language_layers, checkpoint_info


