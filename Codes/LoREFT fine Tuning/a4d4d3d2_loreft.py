def resolve_csv_path(csv_path, dataset_name):
    csv_path = clean_path(csv_path)

    for candidate in csv_path_spelling_variants(csv_path):
        if os.path.isfile(candidate):
            if candidate != csv_path:
                print("\nCSV path repaired:")
                print("Original:", csv_path)
                print("Using   :", candidate)
            return candidate

    patient_id = patient_id_from_dataset_name(dataset_name)

    possible_parent_dirs = []
    for candidate in csv_path_spelling_variants(csv_path):
        possible_parent_dirs.append(os.path.dirname(candidate))

    possible_csvs = []
    for parent_dir in unique_keep_order(possible_parent_dirs):
        if not os.path.isdir(parent_dir):
            continue

        for filename in os.listdir(parent_dir):
            if filename.lower().endswith(".csv"):
                possible_csvs.append(os.path.join(parent_dir, filename))

    possible_csvs = unique_keep_order(possible_csvs)

    if not possible_csvs:
        drive_csvs = search_google_drive_for_csv(csv_path, dataset_name)
        if len(drive_csvs) == 1:
            print("\nCSV found by searching Google Drive:")
            print("Original:", csv_path)
            print("Using   :", drive_csvs[0])
            return drive_csvs[0]
        if len(drive_csvs) > 1:
            print("\nCSV found by searching Google Drive:")
            print("Original:", csv_path)
            print("Using   :", drive_csvs[0])
            print("Other candidates:")
            for candidate in drive_csvs[1:10]:
                print(candidate)
            return drive_csvs[0]

    if len(possible_csvs) == 1:
        print("\nCSV filename repaired from the containing folder:")
        print("Original:", csv_path)
        print("Using   :", possible_csvs[0])
        return possible_csvs[0]

    if len(possible_csvs) > 1:
        scored = sorted(
            [
                (score_csv_candidate(candidate, patient_id), candidate)
                for candidate in possible_csvs
            ],
            reverse=True,
        )

        best_score, best_candidate = scored[0]
        tied_best = [
            candidate
            for score, candidate in scored
            if score == best_score
        ]

        if best_score > 0 and len(tied_best) == 1:
            print("\nCSV filename repaired from the containing folder:")
            print("Original:", csv_path)
            print("Using   :", best_candidate)
            return best_candidate

        print("\nCSV does not exist, and multiple CSV files were found in the folder.")
        print("Please choose the correct one from these candidates:")
        for _, candidate in scored:
            print(candidate)

    raise FileNotFoundError(f"\nCSV does not exist:\n{csv_path}")


def unique_keep_order(values):
    seen = set()
    ordered = []

    for value in values:
        if value is None:
            continue

        value = str(value).strip()
        if not value:
            continue

        if value not in seen:
            seen.add(value)
            ordered.append(value)

    return ordered


def filename_candidates_from_row(row, image_column):
    candidates = []

    for column in row.index:
        lower = str(column).lower()
        if "filename" in lower or lower in {"file", "image_name", "image"}:
            value = clean_path(row[column])
            if value:
                candidates.append(os.path.basename(value))

    original_path = clean_path(row[image_column])
    if original_path:
        candidates.append(os.path.basename(original_path))

    return unique_keep_order(candidates)


