def normalize_ground_truth_label(value):
    if pd.isna(value):
        return None

    if isinstance(value, (int, np.integer)):
        if int(value) == 1:
            return 1
        if int(value) == 0:
            return 0

    if isinstance(value, (float, np.floating)):
        if float(value) == 1.0:
            return 1
        if float(value) == 0.0:
            return 0

    text = str(value).strip().lower()
    text = text.replace("_", " ").replace("–", "-")
    text = re.sub(r"\s+", " ", text)

    if text in {"0", "0.0", "non seizure", "non-seizure", "nonseizure", "normal", "interictal", "ns"}:
        return 0
    if "non" in text and "seizure" in text:
        return 0
    if text in {"1", "1.0", "seizure", "ictal", "sz"}:
        return 1
    if "seizure" in text:
        return 1

    return None


def label_inference_columns(df):
    priority_columns = []

    for column in df.columns:
        lower = str(column).lower()

        if any(token in lower for token in ["label", "target", "category"]):
            priority_columns.append(column)
            continue

        if "class" in lower and "position" not in lower:
            priority_columns.append(column)
            continue

    for column in df.columns:
        lower = str(column).lower()

        if lower in {"filename", "file_name", "image_filename", "blinded_filename"}:
            priority_columns.append(column)
            continue

        if (
            ("filename" in lower or "path" in lower)
            and
            ("image" in lower or "topomap" in lower or "blind" in lower or "original" in lower)
        ):
            priority_columns.append(column)

    return unique_keep_order(priority_columns)


def infer_ground_truth_label_from_row(row, columns):
    for column in columns:
        label = normalize_ground_truth_label(row[column])
        if label is not None:
            return label

    return None


