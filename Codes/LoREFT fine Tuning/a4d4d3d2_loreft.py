def find_language_layers(multimodal_model):
    candidates = []

    if hasattr(multimodal_model, "model"):
        outer = multimodal_model.model
        if hasattr(outer, "language_model"):
            candidates.append(("model.language_model", outer.language_model))
        if hasattr(outer, "text_model"):
            candidates.append(("model.text_model", outer.text_model))

    if hasattr(multimodal_model, "language_model"):
        candidates.append(("language_model", multimodal_model.language_model))

    if hasattr(multimodal_model, "text_model"):
        candidates.append(("text_model", multimodal_model.text_model))

    for base_path, language_model in candidates:
        if hasattr(language_model, "layers") and isinstance(language_model.layers, nn.ModuleList):
            return language_model, language_model.layers, f"{base_path}.layers"

        if hasattr(language_model, "model"):
            nested = language_model.model
            if hasattr(nested, "layers") and isinstance(nested.layers, nn.ModuleList):
                return language_model, nested.layers, f"{base_path}.model.layers"

    for module_name, module in multimodal_model.named_modules():
        if (
            isinstance(module, nn.ModuleList)
            and module_name.endswith("layers")
            and "language_model" in module_name.lower()
            and "vision" not in module_name.lower()
        ):
            return None, module, module_name

    raise RuntimeError("Could not locate MedGemma's language transformer stack.")


class LowRankRotateLayer(nn.Module):
    def __init__(self, input_dim, rank):
        super().__init__()
        self.weight = nn.Parameter(torch.empty(input_dim, rank), requires_grad=True)
        nn.init.orthogonal_(self.weight)

    def forward(self, x):
        return torch.matmul(x.to(self.weight.dtype), self.weight)


class LoReFTIntervention(nn.Module):
    def __init__(self, embed_dim, rank, train_dtype=torch.float32, dropout=0.0):
        super().__init__()

        rotate_layer = LowRankRotateLayer(embed_dim, rank).to(dtype=train_dtype)
        self.rotate_layer = nn.utils.parametrizations.orthogonal(rotate_layer)
        self.learned_source = nn.Linear(embed_dim, rank, bias=True).to(dtype=train_dtype)
        self.dropout = nn.Dropout(dropout)

        with torch.no_grad():
            current_rotation = self.rotate_layer.weight.detach().to(
                dtype=self.learned_source.weight.dtype,
                device=self.learned_source.weight.device,
            )
            self.learned_source.weight.copy_(current_rotation.T)
            self.learned_source.bias.zero_()

        self._capture_precision_diagnostic = False
        self._last_precision_diagnostic = None

    def arm_precision_diagnostic(self):
        self._capture_precision_diagnostic = True
        self._last_precision_diagnostic = None

    def get_precision_diagnostic(self):
        return self._last_precision_diagnostic

    def forward(self, base):
        original_dtype = base.dtype
        autocast_device_type = "cuda" if base.is_cuda else "cpu"

        with torch.autocast(device_type=autocast_device_type, enabled=False):
            base_fp32 = base.float()

            if self.rotate_layer.weight.dtype != torch.float32:
                raise RuntimeError(f"LoReFT rotate_layer weight is not FP32: {self.rotate_layer.weight.dtype}")
            if self.learned_source.weight.dtype != torch.float32:
                raise RuntimeError(f"LoReFT learned_source weight is not FP32: {self.learned_source.weight.dtype}")

            rotated_base_fp32 = self.rotate_layer(base_fp32)
            learned_source_fp32 = self.learned_source(base_fp32)
            delta_fp32 = torch.matmul(
                learned_source_fp32 - rotated_base_fp32,
                self.rotate_layer.weight.T,
            )
            updated_fp32 = base_fp32 + delta_fp32

        updated = updated_fp32.to(dtype=original_dtype)

        if self._capture_precision_diagnostic:
            with torch.no_grad():
                base_detached_fp32 = base.detach().float()
                raw_delta = delta_fp32.detach().float()
                updated_detached_fp32 = updated.detach().float()
                effective_delta = updated_detached_fp32 - base_detached_fp32

                raw_norm = float(raw_delta.norm().cpu())
                effective_norm = float(effective_delta.norm().cpu())
                cast_error_norm = float((raw_delta - effective_delta).norm().cpu())
                changed_fraction = float((updated.detach() != base.detach()).float().mean().cpu())
                retained_ratio = effective_norm / raw_norm if raw_norm > 0.0 else 0.0

                self._last_precision_diagnostic = {
                    "base_dtype": str(base.dtype),
                    "reft_dtype": str(delta_fp32.dtype),
                    "raw_fp32_delta_norm": raw_norm,
                    "effective_post_cast_delta_norm": effective_norm,
                    "cast_error_norm": cast_error_norm,
                    "retained_norm_ratio": retained_ratio,
                    "changed_element_fraction": changed_fraction,
                    "raw_fp32_delta_mean_abs": float(raw_delta.abs().mean().cpu()),
                    "effective_post_cast_delta_mean_abs": float(effective_delta.abs().mean().cpu()),
                }

            self._capture_precision_diagnostic = False

        return self.dropout(updated)


class LoReFTPositionController:
    def __init__(self, prefix_tokens, suffix_tokens):
        self.prefix_tokens = int(prefix_tokens)
        self.suffix_tokens = int(suffix_tokens)
        self.active = False
        self.prompt_length = None
        self.minimum_sequence_length = None

    def activate(self, prompt_length, minimum_sequence_length=None):
        self.prompt_length = int(prompt_length)
        self.minimum_sequence_length = int(minimum_sequence_length if minimum_sequence_length is not None else prompt_length)
        self.active = True

    def deactivate(self):
        self.active = False
        self.prompt_length = None
        self.minimum_sequence_length = None

    def get_positions(self, current_sequence_length):
        if not self.active:
            return []
        if current_sequence_length < self.minimum_sequence_length:
            return []

        prompt_length = min(self.prompt_length, int(current_sequence_length))
        prefix = list(range(min(self.prefix_tokens, prompt_length)))
        suffix = list(range(max(0, prompt_length - self.suffix_tokens), prompt_length))

        positions = []
        seen = set()
        for position in prefix + suffix:
            if position not in seen:
                seen.add(position)
                positions.append(position)

        return positions


def _extract_hidden(layer_output):
    if torch.is_tensor(layer_output):
        return layer_output
    if isinstance(layer_output, (tuple, list)) and len(layer_output) > 0 and torch.is_tensor(layer_output[0]):
        return layer_output[0]
    raise TypeError(f"Unsupported language-layer output type: {type(layer_output)}")


def _replace_hidden(layer_output, new_hidden):
    if torch.is_tensor(layer_output):
        return new_hidden
    if isinstance(layer_output, tuple):
        return (new_hidden,) + tuple(layer_output[1:])
    if isinstance(layer_output, list):
        return [new_hidden] + list(layer_output[1:])
    raise TypeError(f"Unsupported language-layer output type: {type(layer_output)}")


def make_loreft_hook(intervention, controller):
    def hook(module, inputs, output):
        hidden = _extract_hidden(output)

        if hidden.ndim != 3:
            raise RuntimeError(f"Expected [batch, sequence, hidden], got {tuple(hidden.shape)}")

        positions = controller.get_positions(hidden.shape[1])
        if not positions:
            return output

        position_tensor = torch.tensor(positions, dtype=torch.long, device=hidden.device)
        selected = hidden.index_select(1, position_tensor)
        modified = intervention(selected)

        new_hidden = hidden.clone()
        new_hidden[:, position_tensor, :] = modified
        return _replace_hidden(output, new_hidden)

    return hook


class MedGemmaLoReFTWrapper(nn.Module):
    def __init__(self, base, controller, interventions, checkpoint_info):
        super().__init__()
        self.base_model = base
        self.controller = controller
        self.checkpoint_info = dict(checkpoint_info)
        object.__setattr__(self, "_interventions_ref", interventions)

    @property
    def config(self):
        return self.base_model.config

    def forward(self, *args, **kwargs):
        labels = kwargs.get("labels", None)

        if labels is not None:
            if labels.ndim != 2 or labels.shape[0] != 1:
                raise ValueError("This LoReFT pipeline expects physical batch size = 1.")

            supervised_positions = torch.nonzero(labels[0] != -100, as_tuple=False).flatten()
            if supervised_positions.numel() == 0:
                raise RuntimeError("No assistant target token was found in the loss mask.")

            prompt_length = int(supervised_positions[0].item())
        else:
            input_ids = kwargs.get("input_ids", None)
            if input_ids is None:
                raise RuntimeError("LoReFT forward needs labels or input_ids to determine prompt positions.")
            prompt_length = int(input_ids.shape[1])

        self.controller.activate(prompt_length=prompt_length, minimum_sequence_length=prompt_length)
        return self.base_model(*args, **kwargs)

    @torch.no_grad()
    def generate(self, *args, **kwargs):
        input_ids = kwargs.get("input_ids", None)
        if input_ids is None:
            raise RuntimeError("generate() requires input_ids for LoReFT position control.")

        prompt_length = int(input_ids.shape[1])
        self.controller.activate(prompt_length=prompt_length, minimum_sequence_length=prompt_length)

        try:
            return self.base_model.generate(*args, **kwargs)
        finally:
            self.controller.deactivate()

    def save_pretrained(self, save_directory, safe_serialization=True, **kwargs):
        os.makedirs(save_directory, exist_ok=True)

        multi_layer_state = {
            layer_key: intervention.state_dict()
            for layer_key, intervention in self._interventions_ref.items()
        }

        torch.save(multi_layer_state, os.path.join(save_directory, "loreft_intervention.pt"))

        with open(os.path.join(save_directory, "loreft_config.json"), "w", encoding="utf-8") as file:
            json.dump(self.checkpoint_info, file, indent=4)


def resolve_loreft_model_info(multimodal_model, target_layers_human):
    language_model_object, language_layers, language_layers_path = find_language_layers(multimodal_model)
    num_language_layers = len(language_layers)

    target_layers_human = [int(x) for x in target_layers_human]
    if len(target_layers_human) != len(set(target_layers_human)):
        raise ValueError("Duplicate LoReFT target layers were requested.")

    for human_layer in target_layers_human:
        if human_layer < 1 or human_layer > num_language_layers:
            raise ValueError(f"Requested LoReFT layer {human_layer}, but the language model has {num_language_layers} layers.")

    target_layer_indices = [human_layer - 1 for human_layer in target_layers_human]

    if hasattr(multimodal_model.config, "text_config") and hasattr(multimodal_model.config.text_config, "hidden_size"):
        hidden_size = int(multimodal_model.config.text_config.hidden_size)
    elif language_model_object is not None and hasattr(language_model_object, "config"):
        hidden_size = int(language_model_object.config.hidden_size)
    else:
        raise RuntimeError("Could not determine the language hidden size.")

    return {
        "language_model_object": language_model_object,
        "language_layers": language_layers,
        "language_layers_path": language_layers_path,
        "num_language_layers": num_language_layers,
        "hidden_size": hidden_size,
        "target_layers_human": target_layers_human,
        "target_layer_indices": target_layer_indices,
    }


def attach_loreft(
    base,
    target_layers_human,
    rank,
    prefix_tokens,
    suffix_tokens,
    dropout,
    trainable,
    saved_state=None,
    saved_config=None,
):
    info = resolve_loreft_model_info(base, target_layers_human)
    language_layers = info["language_layers"]
    target_layer_indices = info["target_layer_indices"]

    controller = LoReFTPositionController(prefix_tokens=prefix_tokens, suffix_tokens=suffix_tokens)
    target_language_layers = []
    interventions = {}
    hook_handles = []

    for human_layer, python_index in zip(info["target_layers_human"], target_layer_indices):
        layer_key = str(human_layer)
        target_layer = language_layers[python_index]

        intervention = LoReFTIntervention(
            embed_dim=info["hidden_size"],
            rank=rank,
            train_dtype=torch.float32,
            dropout=dropout,
        ).to(DEVICE)

        target_layer.add_module(LOREFT_MODULE_NAME, intervention)

        if saved_state is not None:
            if layer_key not in saved_state:
                raise RuntimeError(f"Missing saved LoReFT state for human layer {human_layer}.")
            intervention.load_state_dict(saved_state[layer_key], strict=True)

        for parameter in intervention.parameters():
            parameter.requires_grad = bool(trainable)

        hook_handle = target_layer.register_forward_hook(make_loreft_hook(intervention, controller))

        target_language_layers.append(target_layer)
        interventions[layer_key] = intervention
        hook_handles.append(hook_handle)

    checkpoint_info = {
        "method": "LoReFT",
        "variant": "multi_layer_independent_interventions",
        "formula": "h + R^T(Wh + b - Rh)",
        "rank": rank,
        "num_language_layers": info["num_language_layers"],
        "target_layers_human": info["target_layers_human"],
        "target_layer_python_indices": target_layer_indices,
        "num_interventions": len(target_layer_indices),
        "hidden_size": info["hidden_size"],
        "prefix_prompt_tokens": prefix_tokens,
        "suffix_prompt_tokens": suffix_tokens,
        "dropout": dropout,
        "component": LOREFT_COMPONENT,
        "language_layers_path": info["language_layers_path"],
        "precision_fix": "autocast disabled inside LoReFT; true FP32 projection + FP32 residual addition; one final cast to model dtype",
        "initialization": "identity_no_op_W_equals_R_transpose_bias_zero",
        "bf16_diagnostic": True,
        "rotation_weight_decay": 0.0,
        "source_weight_decay": WEIGHT_DECAY,
        "source_bias_weight_decay": 0.0,
    }

    if saved_config is not None:
        checkpoint_info.update(saved_config)

    wrapper = MedGemmaLoReFTWrapper(
        base=base,
        controller=controller,
        interventions=interventions,
        checkpoint_info=checkpoint_info,
    ).to(DEVICE)

    return wrapper, info, controller, interventions, hook_handles, target_language_layers, checkpoint_info


