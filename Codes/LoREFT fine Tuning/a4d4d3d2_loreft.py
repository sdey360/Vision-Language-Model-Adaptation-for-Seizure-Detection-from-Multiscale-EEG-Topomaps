def patient_id_from_dataset_name(dataset_name):
    match = re.search(r"patient\s+(\d+)", str(dataset_name), flags=re.IGNORECASE)
    if match is None:
        return None
    return match.group(1).lstrip("0") or "0"


def score_csv_candidate(csv_path, patient_id):
    basename = os.path.basename(csv_path).lower()
    score = 0

    if "blind" in basename:
        score += 20
    text = str(csv_path).replace("\\", "/").lower()

    if "a4d4d3d2" in text:
        score += 30
    if "raw" in basename or "a1" in basename or "a4d4d3d2" in basename:
        score += 10
    if "label" in basename:
        score += 5

    if patient_id is not None:
        patient_tokens = {
            patient_id,
            patient_id.zfill(2),
            f"patient_{patient_id}",
            f"patient_{patient_id.zfill(2)}",
            f"patient{patient_id}",
            f"patient{patient_id.zfill(2)}",
        }
        if any(token.lower() in basename for token in patient_tokens):
            score += 50

    return score

