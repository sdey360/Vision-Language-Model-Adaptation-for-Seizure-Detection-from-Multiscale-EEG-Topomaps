def search_google_drive_for_csv(csv_path, dataset_name):
    representation = globals().get("REPRESENTATION_NAME", "A4D4D3D2").lower()
    patient_id = patient_id_from_dataset_name(dataset_name)
    expected_basename = os.path.basename(clean_path(csv_path)).lower()

    matches = []
    roots = available_drive_search_roots()

    if not roots:
        return matches

    patient_tokens = []
    if patient_id is not None:
        patient_tokens = [
            patient_id,
            patient_id.zfill(2),
            f"patient {patient_id}",
            f"patient {patient_id.zfill(2)}",
            f"patient_{patient_id}",
            f"patient_{patient_id.zfill(2)}",
            f"patient{patient_id}",
            f"patient{patient_id.zfill(2)}",
        ]

    for root in roots:
        for dirpath, _, filenames in os.walk(root):
            dir_text = dirpath.replace("\\", "/").lower()

            if representation not in dir_text:
                continue

            if patient_tokens and not any(token in dir_text for token in patient_tokens):
                continue

            if patient_id is None and "training" not in dir_text:
                continue

            for filename in filenames:
                if not filename.lower().endswith(".csv"):
                    continue

                candidate = os.path.join(dirpath, filename)
                candidate_text = candidate.replace("\\", "/").lower()

                if representation not in candidate_text:
                    continue

                if patient_tokens and not any(token in candidate_text for token in patient_tokens):
                    continue

                if patient_id is None:
                    if "training" not in candidate_text:
                        continue
                else:
                    if "blind" not in candidate_text and "test" not in candidate_text:
                        continue

                score = score_csv_candidate(candidate, patient_id)
                if filename.lower() == expected_basename:
                    score += 100
                if representation in filename.lower():
                    score += 30
                if "label" in filename.lower():
                    score += 10
                if "metadata" in filename.lower():
                    score += 5
                if "blind" in candidate_text:
                    score += 10
                if "test" in candidate_text:
                    score += 5
                if "training" in candidate_text and patient_id is None:
                    score += 20

                matches.append((score, candidate))

    matches = sorted(matches, reverse=True)
    return unique_keep_order([candidate for _, candidate in matches])


