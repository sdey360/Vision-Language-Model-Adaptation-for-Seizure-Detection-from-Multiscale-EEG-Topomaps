def metrics(frame, seizure_probability):
    y = frame.label.to_numpy(int); p = np.asarray(seizure_probability, float) > .5
    tp = int(((y == 1) & p).sum()); fn = int(((y == 1) & ~p).sum())
    tn = int(((y == 0) & ~p).sum()); fp = int(((y == 0) & p).sum())
    if tp + fn == 0 or tn + fp == 0:
        raise ValueError('Both true classes are needed for these diagnostics.')
    sensitivity, specificity = tp / (tp + fn), tn / (tn + fp)
    return {'n': len(y), 'TN': tn, 'FP': fp, 'FN': fn, 'TP': tp,
            'accuracy': (tp + tn) / len(y), 'balanced_accuracy': (sensitivity + specificity) / 2,
            'sensitivity': sensitivity, 'specificity': specificity,
            'f1': 2 * tp / (2 * tp + fp + fn) if 2 * tp + fp + fn else 0.}

