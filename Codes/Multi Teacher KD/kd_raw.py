def load_raw_folder_metadata():
    """Read current RAW CSV and images directly; old RAW_resolved.csv is never read."""
    global RAW_MANIFEST
    path = find_raw_folder_csv(); RAW_MANIFEST = path
    source = pd.read_csv(path, dtype=str, keep_default_na=False, encoding='utf-8-sig')
    if source.empty: raise ValueError('The RAW input CSV is empty.')
    print('\nRAW METADATA SOURCE:', path, '| rows:', len(source), flush=True)
    print('RAW IMAGE SOURCE:', RAW_IMAGE_ROOT, flush=True)
    print('Historical split column is retained as source_split; current cache bookkeeping is matched by patient/master ID, then original RAW adapter splits determine student training/validation.', flush=True)
    def values(row, aliases):
        return [str(v).strip() for c, v in row.items() if raw_column_key(c) in aliases and str(v).strip()]
    def one(items, normalize, field, number):
        parsed = {normalize(v) for v in items}
