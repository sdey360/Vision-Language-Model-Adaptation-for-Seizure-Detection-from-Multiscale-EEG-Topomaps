def raw_column_key(value):
    return re.sub(r'[^a-z0-9]', '', str(value).lower())


def raw_integer_id(value, prefix=''):
    text = str(value).strip()
    match = re.fullmatch(r'(?:' + re.escape(prefix) + r')?(\d+)(?:\.0+)?', text, flags=re.I)
    if not match: raise ValueError(f'Invalid original identifier: {value!r}')
    return str(int(match.group(1)))


