def move_batch(batch):
    return {k:v.to('cuda:0',dtype=DTYPE if v.is_floating_point() else v.dtype) for k,v in batch.items()}

def candidate_batches(processor,row,rep):
    path=row['local_image_path'] if Path(row['local_image_path']).is_file() else row['image_path']
    with Image.open(path) as opened:
        messages=chat_for(opened.convert('RGB'),rep)
        kwargs={'tokenize':True,'return_dict':True,'return_tensors':'pt','processor_kwargs':{'do_pan_and_scan':DO_PAN_AND_SCAN}}
        prompt=processor.apply_chat_template(messages,add_generation_prompt=True,**kwargs)
        prefix=prompt['input_ids'];length=prefix.shape[1]
        batches=[]
        for answer in ANSWER_TEXT_BY_REP[rep]:
            full=processor.apply_chat_template(messages+[{'role':'assistant','content':[{'type':'text','text':answer}]}],
                add_generation_prompt=False,**kwargs)
            if full['input_ids'].shape[1]<=length or not torch.equal(full['input_ids'][:,:length],prefix):
                raise RuntimeError('Assistant-answer prefix mismatch; prompt masking would be unsafe.')
            if full['input_ids'].shape[1]>MAX_INPUT_TOKENS:raise ValueError('Input exceeds MAX_INPUT_TOKENS; no truncation applied.')
            targets=full['input_ids'][:,length:].clone()
            batches.append((full,targets,length))
    return batches

def candidate_scores(model,processor,row,rep,return_audit=False):
    scores,ces,audits=[],[],[]
    for cpu_batch,cpu_targets,length in candidate_batches(processor,row,rep):
        batch=move_batch(cpu_batch);targets=cpu_targets.to('cuda:0')
        positions=torch.arange(length-1,batch['input_ids'].shape[1]-1,device='cuda:0')
        with torch.autocast('cuda',dtype=DTYPE):
            output=model(**batch,use_cache=False,logits_to_keep=positions)
        logits=output.logits
        if logits.shape[:2]!=targets.shape:raise RuntimeError('Candidate token positions/logits do not align.')
        nll=F.cross_entropy(logits.float().reshape(-1,logits.shape[-1]),targets.reshape(-1),reduction='none')
        scores.append(-nll.sum());ces.append(nll.mean())
        audits.append({'answer_text':ANSWER_TEXT_BY_REP[rep][len(audits)],'answer_tokens':targets.detach().cpu().tolist()[0],
                       'decoded_answer':processor.tokenizer.decode(cpu_targets[0]),'prompt_tokens':length})
        del output,logits,nll,batch,targets
    scores=torch.stack(scores);ces=torch.stack(ces)
    if not bool(torch.isfinite(scores).all()):raise FloatingPointError('Nonfinite candidate label scores.')
    return (scores,ces,audits) if return_audit else (scores,ces)

def probabilities(scores,temperature=1.0):
    return F.softmax(scores.float()/temperature,dim=-1)

def kd_loss(scores,target):
    target=torch.as_tensor(target,device=scores.device,dtype=torch.float32).detach()
    if target.shape!=(2,) or not bool(torch.isfinite(target).all()) or bool((target<0).any()) or not torch.allclose(target.sum(),target.new_tensor(1.),atol=1e-5):
        raise ValueError('Invalid two-class teacher target.')
    logp=F.log_softmax(scores.float()/KD_TEMPERATURE,dim=-1)
    # torch.xlogy defines 0*log(0) correctly; average is over examples, not classes.
    value=(torch.xlogy(target,target)-target*logp).sum()*KD_TEMPERATURE**2
    if not bool(torch.isfinite(value)) or float(value.detach()) < -1e-4:raise FloatingPointError('Invalid KL divergence.')
    return value.clamp_min(0.)

def build_student(adapter=None):
    """Default: continue the exact RAW adapter; an explicit path is frozen eval."""
    training = adapter is None
    source = RAW_ADAPTER if training else Path(adapter)
    config = load_json(source / 'adapter_config.json')
    if config.get('kasa_config') is not None: raise ValueError('Active KaSA is not supported.')
    base = new_base(training)
    with warnings.catch_warnings():
        warnings.filterwarnings('ignore', message=r"Unexpected keyword arguments \['kasa_config'\] for class LoraConfig,.*")
        model = PeftModel.from_pretrained(base, str(source), is_trainable=training)
    del base
    processor = get_processor(source)
    expected = load_file(str(source / 'adapter_model.safetensors'), device='cpu')
    actual = get_peft_model_state_dict(model)
    if set(expected) != set(actual): raise RuntimeError('Loaded RAW adapter keys differ from the saved checkpoint.')
    for name in expected:
        if expected[name].shape != actual[name].shape or not torch.equal(expected[name].float(), actual[name].detach().cpu().float()):
            raise RuntimeError(f'Loaded adapter tensor differs from its saved value: {name}')
    del expected, actual
    if training:
        trainable = [(name, p) for name, p in model.named_parameters() if p.requires_grad]
        if not trainable or any('lora_' not in name or 'vision' in name or 'multi_modal_projector' in name for name, p in trainable):
            raise RuntimeError('Expected only the existing RAW language-adapter parameters to be trainable.')
        model.print_trainable_parameters()
    else:
        model.requires_grad_(False); model.eval(); model.gradient_checkpointing_disable()
    return model, processor


def evaluate_model(model, processor, frame, description, prefix=None, data_signature=''):
    """Resumable inference; no validation/test gradient updates."""
    was_training = model.training; model.eval()
    metadata = {'data_signature': data_signature, 'adapter_sha256': tensor_state_hash(adapter_state(model)),
                'evaluation_context': EVALUATION_CONTEXT,
                'processor_signature': processor_signature(processor, 'RAW'),
                'rows': frame[['uid', 'patient_id', 'label']].to_dict('records')}
    signature = json_hash(metadata)
    records = []; resource_history = []
    prefix = Path(prefix) if prefix is not None else None
    if prefix is not None:
        protocol_path = prefix.with_name(prefix.name + '_evaluation_protocol.json')
        prediction_path = prefix.with_name(prefix.name + '_predictions.csv')
        resources_path = prefix.with_name(prefix.name + '_resources.json')
        if protocol_path.exists() and load_json(protocol_path).get('signature') != signature:
            raise RuntimeError('Evaluation data/model changed; cached predictions cannot be mixed.')
        save_json(protocol_path, {**metadata, 'signature': signature})
        if resources_path.exists(): resource_history = load_json(resources_path).get('calls', [])
        if prediction_path.exists():
            old = pd.read_csv(prediction_path, dtype={'uid': str, 'patient_id': str, 'master_id': str, 'global_serial': str}, keep_default_na=False)
            if old.uid.duplicated().any() or not set(old.uid) <= set(frame.uid):
                raise ValueError('Evaluation cache has duplicate/unexpected IDs.')
            if 'evaluation_signature' not in old or not (old.evaluation_signature == signature).all():
                raise ValueError('Evaluation cache signature mismatch.')
            expected = frame.set_index('uid')
            for row in old.itertuples():
                if int(row.label) != int(expected.at[row.uid, 'label']) or row.patient_id != expected.at[row.uid, 'patient_id']:
                    raise ValueError('Evaluation cache identities/labels changed.')
            values = old[['score_0', 'score_1', 'probability_0', 'probability_1', 'label_ce']].to_numpy(float)
            if not np.isfinite(values).all() or not old.predicted_label.isin([0, 1]).all():
                raise ValueError('Invalid cached evaluation predictions.')
            if not np.allclose(values[:, 2:4].sum(axis=1), 1., atol=1e-6):
                raise ValueError('Invalid cached evaluation probabilities.')
            if (values[:, 2:4] < 0).any() or (values[:, 2:4] > 1).any():
                raise ValueError('Cached evaluation probabilities are outside [0,1].')
            shifted = values[:, :2] - values[:, :2].max(axis=1, keepdims=True)
            expected_probabilities = np.exp(shifted); expected_probabilities /= expected_probabilities.sum(axis=1, keepdims=True)
            if not np.allclose(values[:, 2:4], expected_probabilities, atol=2e-6, rtol=2e-5):
                raise ValueError('Cached evaluation probabilities disagree with stored scores.')
            if not np.array_equal(old.predicted_label.to_numpy(int), (values[:, 1] > values[:, 0]).astype(int)):
                raise ValueError('Cached evaluation labels disagree with stored scores.')
            records = old.to_dict('records')
    done = {r['uid'] for r in records}
    remaining = frame[~frame.uid.isin(done)].to_dict('records')
    phase = start_phase(); completed_now = 0
    try:
        with torch.inference_mode():
            for row in tqdm(remaining, desc=description):
                scores, ce = candidate_scores(model, processor, row, 'RAW')
                s = scores.detach().cpu().tolist(); p = probabilities(scores).cpu().tolist()
                records.append({'uid': row['uid'], 'patient_id': row['patient_id'], 'master_id': row.get('master_id', ''),
                    'global_serial': row.get('global_serial', ''), 'label': int(row['label']),
                    'predicted_label': int(s[1] > s[0]), 'score_0': s[0], 'score_1': s[1],
                    'probability_0': p[0], 'probability_1': p[1], 'label_ce': float(ce[int(row['label'])]),
                    'image_path': row['image_path'], 'evaluation_signature': signature,
                    'evaluation_status': EVALUATION_CONTEXT.get('evaluation_status', 'UNSPECIFIED'),
                    'exploratory': bool(EVALUATION_CONTEXT.get('exploratory', False))})
                completed_now += 1
                if prefix is not None and len(records) % SAVE_CACHE_EVERY == 0:
                    save_csv(prediction_path, pd.DataFrame(records))
                del scores, ce
    finally:
        resource = end_phase(phase)
        resource['images_scored'] = completed_now
        resource_history.append(resource)
        if prefix is not None:
            if records: save_csv(prediction_path, pd.DataFrame(records))
            save_json(resources_path, {'calls': resource_history})
        model.train(was_training)
    result = pd.DataFrame(records)
    if set(result.uid) != set(frame.uid): raise RuntimeError('Incomplete evaluation; rerun to resume.')
    summary, patients = summarize_predictions(result)
    summary['evaluation_context'] = EVALUATION_CONTEXT
    patients['evaluation_status'] = EVALUATION_CONTEXT.get('evaluation_status', 'UNSPECIFIED')
    patients['exploratory'] = bool(EVALUATION_CONTEXT.get('exploratory', False))
    summary['mean_label_ce'] = float(result.label_ce.mean())
    summary['resources'] = {'seconds': sum(r['seconds'] for r in resource_history),
        'peak_allocated_GiB': max(r['peak_allocated_GiB'] for r in resource_history),
        'peak_reserved_GiB': max(r['peak_reserved_GiB'] for r in resource_history)}
    return summary, patients, result


