def stage_raw_images(frame, run_dir, kind):
    result = frame.copy(); located, directory_index = [], None
    root = RAW_IMAGE_ROOT if kind == 'pool' else RAW_TEST_IMAGE_ROOT
    for row in tqdm(result.to_dict('records'), desc=f'Verify/stage RAW {kind}'):
        expected = str(row.get('file_sha256', ''))
        if not re.fullmatch(r'[a-fA-F0-9]{64}', expected):
            raise ValueError(f'RAW image hash missing for {row["uid"]}.')
        destination = LOCAL_IMAGE_ROOT / run_dir.name / kind / (expected + '.png')
        if destination.is_file() and file_hash(destination) == expected:
            located.append(str(destination)); continue
        candidates = [Path(row.get('local_image_path', '')), Path(row['image_path'])]
        source = next((p for p in candidates if p.is_file()), None)
        if source is None:
            if directory_index is None:
                directory_index = {}
                for p in root.rglob('*'):
                    if p.is_file() and p.suffix.lower() in {'.png', '.jpg', '.jpeg', '.tif', '.tiff', '.bmp'}:
                        directory_index.setdefault(p.name.casefold(), []).append(p)
            name = str(row['image_path']).replace('\\', '/').rsplit('/', 1)[-1].casefold()
            matches = [p for p in directory_index.get(name, []) if file_hash(p) == expected]
            source = sorted(matches)[0] if matches else None
        if source is None or file_hash(source) != expected:
            raise ValueError(f'Missing/changed RAW image for {row["uid"]}: {row["image_path"]}')
        destination.parent.mkdir(parents=True, exist_ok=True)
        temporary = destination.with_name(destination.name + '.tmp')
        shutil.copyfile(source, temporary); os.replace(temporary, destination)
        if file_hash(destination) != expected: raise ValueError('RAW staging hash mismatch.')
        located.append(str(destination))
    result['local_image_path'] = located
    return result

def read_id_table(path):
    frame = pd.read_csv(path, dtype=str, keep_default_na=False, encoding='utf-8-sig')
    required = {'uid', 'patient_id', 'master_id', 'label', 'split'}
    if frame.empty or not required <= set(frame):
        raise ValueError(f'Missing identity/label/split columns in {path}.')
    if frame.uid.duplicated().any() or frame.duplicated(['patient_id', 'master_id']).any():
        raise ValueError(f'Duplicate identities in {path}.')
    if (frame[['uid', 'patient_id', 'master_id']] == '').any().any():
        raise ValueError(f'Empty patient/master/window identity in {path}.')
    numeric = pd.to_numeric(frame.label, errors='raise')
    if not numeric.isin([0, 1]).all(): raise ValueError(f'Invalid labels in {path}.')
    frame['label'] = numeric.astype(int)
    return frame


def match_ids(frame, expected, description):
    if set(frame.uid) != set(expected.uid):
        raise ValueError(f'{description}: window IDs differ; do not take a silent intersection.')
    columns = ['patient_id', 'master_id', 'label', 'split']
    left = frame.set_index('uid')[columns].sort_index()
    right = expected.set_index('uid')[columns].sort_index()
    if not left.equals(right):
        raise ValueError(f'{description}: patient/master ID, label or split mismatch.')


