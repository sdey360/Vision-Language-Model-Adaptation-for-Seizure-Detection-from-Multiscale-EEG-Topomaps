def read_teacher_cache(rep, directory, raw):
    protocol = load_json(directory / f'{rep}_protocol.json')
    status = load_json(directory / f'{rep}_cache_status.json')
    signature = protocol.get('signature')
    unsigned = {k: v for k, v in protocol.items() if k != 'signature'}
    if signature != json_hash(unsigned): raise ValueError(f'{rep}: protocol signature is invalid.')
    expected_signature = EXPECTED_PROTOCOL_SIGNATURES.get(rep)
    if expected_signature and signature != expected_signature:
        raise ValueError(f'{rep}: protocol differs from the exact completed cache supplied by the user.')
    expected_adapter = RESULTS_ROOT / rep / TEACHER_STAMPS[rep] / 'best_adapter'
    if protocol.get('teacher') != rep or Path(protocol.get('adapter_path', '')) != expected_adapter:
        raise ValueError(f'{rep}: cache identifies a different teacher adapter.')
    if protocol.get('model_id') != MODEL_ID or status.get('teacher') != rep:
        raise ValueError(f'{rep}: wrong model or teacher in saved metadata.')
    if status.get('complete') is not True or status.get('protocol_signature') != signature:
        raise ValueError(f'{rep}: completion record does not match the cache protocol.')
    answers = protocol.get('answers', [])
    normalized = [re.sub(r'[\s_-]+', '', str(a).lower()) for a in answers]
    if normalized != ['nonseizure', 'seizure']:
        raise ValueError(f'{rep}: class order is not [non-seizure, seizure].')
    temperature = float(protocol['temperature'])
    if not np.isfinite(temperature) or temperature <= 0: raise ValueError('Invalid KD temperature.')
    full = read_id_table(directory / f'{rep}_scores.csv')
    match_ids(full, raw, rep)
    if not {'teacher', 'protocol_signature', 'score_0', 'score_1', 'probability_0', 'probability_1', 'target_0', 'target_1'} <= set(full):
        raise ValueError(f'{rep}: incomplete score fields.')
    if not (full.teacher == rep).all() or not (full.protocol_signature == signature).all():
        raise ValueError(f'{rep}: cache rows belong to another protocol.')
    for col in ('score_0', 'score_1', 'probability_0', 'probability_1', 'target_0', 'target_1'):
        full[col] = pd.to_numeric(full[col], errors='raise').astype(float)
    scores = full[['score_0', 'score_1']].to_numpy(float)
    if not np.isfinite(scores).all(): raise ValueError(f'{rep}: nonfinite scores.')
    for t, cols in ((1., ['probability_0', 'probability_1']), (temperature, ['target_0', 'target_1'])):
        logits = (scores - scores.max(axis=1, keepdims=True)) / t
        expected = np.exp(logits); expected /= expected.sum(axis=1, keepdims=True)
        actual = full[cols].to_numpy(float)
        if not np.isfinite(actual).all() or (actual < 0).any() or (actual > 1).any() or not np.allclose(actual.sum(axis=1), 1., atol=1e-6):
            raise ValueError(f'{rep}: invalid probability distributions.')
        if not np.allclose(actual, expected, atol=2e-6, rtol=2e-5):
            raise ValueError(f'{rep}: targets/probabilities disagree with stored scores.')
    training = read_id_table(directory / f'{rep}_training_targets.csv')
    wanted = full.loc[full.split == 'train']
    match_ids(training, wanted, rep + ' training export')
    for col in ('target_0', 'target_1'):
        if col not in training: raise ValueError(f'{rep}: missing exported training target.')
        a = pd.to_numeric(training.set_index('uid')[col], errors='raise').sort_index().to_numpy(float)
        b = wanted.set_index('uid')[col].sort_index().to_numpy(float)
        if not np.allclose(a, b, atol=2e-6): raise ValueError(f'{rep}: exported targets differ from full scores.')
    if (int(status['all_rows']) != len(full) or int(status['training_rows']) != len(wanted)
            or int(status['validation_rows']) != int((full.split == 'validation').sum())):
        raise ValueError(f'{rep}: saved completion counts disagree with the CSV.')
    return full, protocol


