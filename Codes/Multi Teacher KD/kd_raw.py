def validation_decision(score, val_ce, state):
    ba_improved = score > state['best_BA'] + MIN_DELTA
    checkpoint_improved = ba_improved or (abs(score - state['best_BA']) <= MIN_DELTA and val_ce < state['best_CE'] - MIN_DELTA)
    next_stale = 0 if ba_improved else state['stale'] + 1
    return bool(ba_improved), bool(checkpoint_improved), next_stale

def cpu_tree(value):
    if isinstance(value,torch.Tensor):return value.detach().cpu()
    if isinstance(value,dict):return {k:cpu_tree(v) for k,v in value.items()}
    if isinstance(value,list):return [cpu_tree(v) for v in value]
    if isinstance(value,tuple):return tuple(cpu_tree(v) for v in value)
    return value

def adapter_state(model):
    return {k:v.detach().cpu().clone() for k,v in get_peft_model_state_dict(model).items()}

def tensor_state_hash(state):
    h=hashlib.sha256()
    for name,value in sorted(state.items()):
        value=value.detach().cpu().contiguous()
        h.update(name.encode());h.update(str(value.dtype).encode());h.update(str(tuple(value.shape)).encode())
        h.update(value.view(torch.uint8).numpy().tobytes())
    return h.hexdigest()

def apply_adapter_state(model,state):
    expected=get_peft_model_state_dict(model)
    if set(state)!=set(expected):raise RuntimeError('Adapter checkpoint keys differ from the configured student architecture.')
    if any(state[k].shape!=expected[k].shape for k in state):raise RuntimeError('Adapter checkpoint shapes differ.')
    set_peft_model_state_dict(model,state)
    if tensor_state_hash(adapter_state(model))!=tensor_state_hash(state):raise RuntimeError('Adapter checkpoint was not restored exactly.')

def rng_state():
    return {'python':random.getstate(),'numpy':np.random.get_state(),'torch':torch.get_rng_state(),'cuda':torch.cuda.get_rng_state_all()}

def restore_rng(state):
    random.setstate(state['python']);np.random.set_state(state['numpy']);torch.set_rng_state(state['torch'])
    torch.cuda.set_rng_state_all(state['cuda'])

def save_checkpoint(path,model,optimizer,scheduler,scaler,state,signature):
    checkpoint={'signature':signature,'adapter':adapter_state(model),'optimizer':cpu_tree(optimizer.state_dict()),
                'scheduler':scheduler.state_dict(),'scaler':scaler.state_dict(),'state':state,'rng':rng_state()}
    temp=path.with_name(path.name+'.tmp')
    torch.save(checkpoint,temp);os.replace(temp,path)

