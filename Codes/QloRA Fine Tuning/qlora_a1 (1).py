class Collator:
    def __init__(self, processor):
        self.processor = processor

    def __call__(self, rows):
        if len(rows) != 1:
            raise ValueError("Physical batch size must be 1, matching the reference LoRA run.")
        row = rows[0]
        with Image.open(row["image_path"]) as opened:
            chat = messages(opened.convert("RGB"))
            prompt = self.processor.apply_chat_template(chat, add_generation_prompt=True,
                tokenize=True, return_dict=True, return_tensors="pt")
            target = "Seizure" if row["label"] == 1 else "Non-seizure"
            full = self.processor.apply_chat_template(chat + [{"role": "assistant", "content": [{"type": "text", "text": target}]}],
                add_generation_prompt=False, tokenize=True, return_dict=True, return_tensors="pt")
        length = prompt["input_ids"].shape[1]
        if full["input_ids"].shape[1] <= length or not torch.equal(full["input_ids"][:, :length], prompt["input_ids"]):
            raise RuntimeError("Chat-template prefix mismatch; cannot safely mask the prompt.")
        labels = full["input_ids"].clone()
        labels[:, :length] = -100
        labels[full["attention_mask"] == 0] = -100
        full["labels"] = labels
        return full


def to_gpu(batch, dtype):
    # Keep token indices and attention masks integer; cast floating image tensors only.
    return {k: v.to(device="cuda:0", dtype=dtype if v.is_floating_point() else v.dtype)
            for k, v in batch.items()}


