def classification_metrics(truth, predictions):
    truth = np.asarray(truth, dtype=int)
    # Preserve your LoRA scoring convention: invalid generations count as wrong.
    # Never replace the recorded model output with this scoring-only fallback.
    scored = np.asarray([p if p is not None else 1 - int(y) for y, p in zip(truth, predictions)], dtype=int)
    tn = int(((truth == 0) & (scored == 0)).sum())
    fp = int(((truth == 0) & (scored == 1)).sum())
    fn = int(((truth == 1) & (scored == 0)).sum())
    tp = int(((truth == 1) & (scored == 1)).sum())
    sensitivity = tp / (tp + fn)
    specificity = tn / (tn + fp)
    precision = tp / (tp + fp) if tp + fp else 0.0
    f1 = 2 * tp / (2 * tp + fp + fn) if 2 * tp + fp + fn else 0.0
    return {"test_images": len(truth), "TN": tn, "FP": fp, "FN": fn, "TP": tp,
            "accuracy": (tp + tn) / len(truth), "balanced_accuracy": (sensitivity + specificity) / 2,
            "sensitivity": sensitivity, "specificity": specificity, "precision": precision, "f1": f1,
            "invalid_outputs": sum(p is None for p in predictions),
            "invalid_output_policy": "count_as_wrong_for_metrics_only"}, scored


def phase_start():
    torch.cuda.synchronize()
    torch.cuda.reset_peak_memory_stats(0)
    return time.perf_counter()


def phase_finish(start):
    torch.cuda.synchronize()
    allocated = int(torch.cuda.max_memory_allocated(0))
    reserved = int(torch.cuda.max_memory_reserved(0))
    return {"seconds": time.perf_counter() - start,
            "peak_allocated_bytes": allocated, "peak_reserved_bytes": reserved,
            "peak_allocated_GiB": allocated / 2**30, "peak_reserved_GiB": reserved / 2**30,
            "peak_allocated_GB": allocated / 1e9, "peak_reserved_GB": reserved / 1e9}


def aggregate_phases(records):
    if not records:
        return {"seconds": 0.0, "peak_allocated_bytes": 0, "peak_reserved_bytes": 0,
                "peak_allocated_GiB": 0.0, "peak_reserved_GiB": 0.0, "peak_allocated_GB": 0.0, "peak_reserved_GB": 0.0}
    allocated = max(x["peak_allocated_bytes"] for x in records)
    reserved = max(x["peak_reserved_bytes"] for x in records)
    return {"seconds": sum(x["seconds"] for x in records),
            "peak_allocated_bytes": allocated, "peak_reserved_bytes": reserved,
            "peak_allocated_GiB": allocated / 2**30, "peak_reserved_GiB": reserved / 2**30,
            "peak_allocated_GB": allocated / 1e9, "peak_reserved_GB": reserved / 1e9}


