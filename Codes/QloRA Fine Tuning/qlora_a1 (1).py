def signature(value):
    text = str(value).replace("\\", "/").split("/")[-1]
    patients = patient_hints(text)
    patient = next(iter(patients)) if len(patients) == 1 else None
    g = re.search(r"(?:^|[_\- ])G(\d+)(?=[_\- .]|$)", text, re.I)
    w = re.search(r"(?:^|[_\- ])W(\d+)(?=[_\- .]|$)", text, re.I)
    edf = re.search(r"chb\d{2}_\d+(?:\+)?(?=[_\-.]|$)", text, re.I)
    return patient, int(g[1]) if g else None, int(w[1]) if w else None, edf[0].lower() if edf else None


def folder_label(path):
    labels = {normalize_label(part) for part in Path(path).parent.parts
              if norm(part) in {"nonseizure", "seizure", "interictal", "ictal"}}
    if len(labels) > 1:
        raise ValueError(f"Conflicting class folders: {path}")
    return next(iter(labels)) if labels else None


class ImageResolver:
    def __init__(self, roots, key):
        self.key = key
        self.roots = [Path(clean_path(p)) for p in roots]
        self.by_name = defaultdict(list)
        self.by_pg = defaultdict(list)
        self.by_pew = defaultdict(list)
        files = set()
        for root in self.roots:
            if not root.is_dir():
                raise FileNotFoundError(f"{key}: image folder does not exist: {root}")
            for directory, dirs, names in os.walk(root):
                dirs[:] = [d for d in dirs if not d.startswith(".")]
                for name in names:
                    p = Path(directory) / name
                    if p.suffix.lower() in IMAGE_SUFFIXES and not has_other_representation(p):
                        files.add(p.resolve())
        for p in sorted(files):
            self.by_name[p.name.casefold()].append(p)
            pid, g, w, edf = signature(p.name)
            if pid and g is not None:
                self.by_pg[(pid, g)].append(p)
            if pid and edf and w is not None:
                self.by_pew[(pid, edf, w)].append(p)
        self.files = files
        print(f"{key}: indexed {len(files)} images in {[str(p) for p in self.roots]}")

    def choose(self, candidates, pid, label, method):
        valid = []
        for p in sorted(set(candidates)):
            hints = patient_hints(str(p))
            if pid and hints and hints != {pid}:
                continue
            actual_label = folder_label(p)
            if actual_label is not None and actual_label != label:
                continue
            valid.append(p)
        if len(valid) == 1:
            return str(valid[0]), method
        if len(valid) > 1:
            raise ValueError(f"Ambiguous {method} match: {[str(p) for p in valid[:6]]}")
        return None

    def resolve(self, raw, filename, pid, label):
        raw = clean_path(raw)
        filename = clean_path(filename).split("/")[-1] if filename else ""
        basename = raw.split("/")[-1] or filename
        names = list(dict.fromkeys(n for n in [basename, filename] if n))
        if not names:
            raise FileNotFoundError("Empty image path and filename")
        # An existing direct path is accepted only within this dataset's roots.
        p = Path(raw)
        if raw.startswith("/") and p.is_file() and p.resolve() in self.files:
            chosen = self.choose([p.resolve()], pid, label, "existing Drive path")
            if chosen:
                return chosen
        exact = [p for n in names for p in self.by_name.get(n.casefold(), [])]
        chosen = self.choose(exact, pid, label, "exact filename")
        if chosen:
            return chosen
        # Known representation-token change, confined to the supplied A1 roots.
        aliases = {re.sub(r"(?<![a-z0-9])raw(?![a-z0-9])", "A1", n, flags=re.I)
                   for n in names}
        aliased = [p for n in aliases for p in self.by_name.get(n.casefold(), [])]
        chosen = self.choose(aliased, pid, label, "RAW-to-A1 filename token")
        if chosen:
            return chosen
        # Renamed files: require patient + global serial, and match window/EDF
        # identifiers as well whenever the source filename supplies them.
        for n in names:
            source_pid, g, w, edf = signature(n)
            expected_pid = pid or source_pid
            if source_pid and pid and source_pid != pid:
                raise ValueError(f"Patient metadata disagrees with filename: {n}")
            if expected_pid and g is not None:
                candidates = self.by_pg.get((expected_pid, g), [])
            elif expected_pid and edf and w is not None:
                candidates = self.by_pew.get((expected_pid, edf, w), [])
            else:
                continue
            candidates = [p for p in candidates
                if (w is None or signature(p.name)[2] == w)
                and (edf is None or signature(p.name)[3] == edf)]
            chosen = self.choose(candidates, expected_pid, label, "patient/window identifiers")
            if chosen:
                return chosen
        raise FileNotFoundError(f"No unique matching image in this dataset's image folders: {raw or filename}")


def load_metadata(csv_path, key):
    df = pd.read_csv(csv_path)
    df.columns = [str(c).strip().lstrip("\ufeff") for c in df.columns]
    overrides = COLUMN_OVERRIDES.get(key, {})
    path_col = pick_column(df, ["blinded_image_path", "image_path", "blinded_path", "topomap_path", "file_path", "filepath", "path"], overrides.get("path"), False)
    name_col = pick_column(df, ["blinded_filename", "blinded_image_name", "blinded_image_filename", "image_filename", "image_name", "filename", "file_name"], overrides.get("filename"), False)
    label_col = pick_column(df, ["true_label", "label", "class_label", "class", "true_class", "class_name", "target", "seizure", "is_seizure"], overrides.get("label"))
    patient_col = pick_column(df, ["patient_id", "patient", "subject_id", "subject"], required=False)
    if df.empty or (path_col is None and name_col is None):
        raise ValueError(f"{key}: empty CSV or missing image path/name column; columns={df.columns.tolist()}")
    labels = df[label_col].map(normalize_label).astype(int)
    for c in df.columns:
        if c != label_col and norm(c) in {"truelabel", "label", "trueclass", "classname", "classlabel"}:
            if not np.array_equal(labels.to_numpy(), df[c].map(normalize_label).to_numpy()):
                raise ValueError(f"{key}: conflicting ground-truth label columns {label_col} and {c}")
    resolver = ImageResolver(IMAGE_ROOTS[key], key)
    RESOLVERS[key] = resolver
    paths, methods, originals = [], [], []
    for i, row in tqdm(df.iterrows(), total=len(df), desc=f"Check ALL {key} images"):
        raw = clean_path(row[path_col]) if path_col else ""
        filename = clean_path(row[name_col]) if name_col else ""
        originals.append(raw or filename)
        try:
            hints = patient_hints(raw or filename)
            if patient_col and pd.notna(row[patient_col]):
                v = str(row[patient_col]).strip()
                hints |= patient_hints(v)
                if re.fullmatch(r"\d+(?:\.0)?", v):
                    hints.add(f"{int(float(v)):02d}")
            if key != "pooled":
                hints.add(key)
            if len(hints) > 1:
                raise ValueError(f"Conflicting patient identities {hints}")
            pid = next(iter(hints)) if hints else None
            resolved, method = resolver.resolve(raw, filename, pid, int(labels.iloc[i]))
            paths.append(resolved)
            methods.append(method)
        except (FileNotFoundError, ValueError) as error:
            paths.append(None)
            methods.append("UNRESOLVED")
            VALIDATION_ISSUES.append({"dataset": key, "source_row": i, "csv": str(csv_path),
                "original_image_path": raw or filename, "label": int(labels.iloc[i]), "problem": str(error),
                "searched_roots": " | ".join(str(p) for p in resolver.roots)})
    out = df.copy()
    out["label"] = labels
    out["original_image_path"] = originals
    out["source_image_path"] = paths
    out["image_path"] = paths
    out["image_match_method"] = methods
    out["source_csv"] = str(csv_path)
    out["source_row"] = np.arange(len(out))
    duplicated = out.source_image_path.notna() & out.source_image_path.duplicated(keep=False)
    for _, row in out[duplicated].iterrows():
        VALIDATION_ISSUES.append({"dataset": key, "source_row": int(row.source_row), "csv": str(csv_path),
            "original_image_path": row.original_image_path, "label": int(row.label),
            "problem": f"Multiple CSV rows resolve to the same image: {row.source_image_path}"})
    if set(labels.unique()) != {0, 1}:
        raise ValueError(f"{key}: both classes are required")
    print(f"{key}: total={len(out)}, NS={(labels == 0).sum()}, S={(labels == 1).sum()}; matches={pd.Series(methods).value_counts().to_dict()}")
    return out


def split_pool(pool):
    # Exact per-class shuffle/ceil/tail split from your saved pooled LoRA code.
    training_parts, validation_parts = [], []
    for label in (0, 1):
        group = pool[pool.label == label].sample(frac=1, random_state=SEED)
        if len(group) < 2:
            raise ValueError("Need at least two pooled examples per class.")
        n_val = max(1, min(len(group) - 1, math.ceil(len(group) * VAL_FRACTION)))
        training_parts.append(group.iloc[:-n_val])
        validation_parts.append(group.iloc[-n_val:])
    return tuple(pd.concat(parts).sample(frac=1, random_state=SEED).reset_index(drop=True)
                 for parts in (training_parts, validation_parts))


def window_keys(df, dataset_key):
    serial_col = pick_column(df, ["global_serial_id", "Global_Serial", "global_serial", "globalserial"], required=False)
    patient_col = pick_column(df, ["patient_id", "patient", "subject_id", "subject"], required=False)
    if serial_col is None:
        return set()
    keys = set()
    for _, row in df.iterrows():
        if pd.isna(row[serial_col]):
            continue
        pid = None
        if patient_col and pd.notna(row[patient_col]):
            v = str(row[patient_col]).strip()
            hints = patient_hints(v)
            if len(hints) == 1:
                pid = next(iter(hints))
            elif re.fullmatch(r"\d+(?:\.0)?", v):
                pid = f"{int(float(v)):02d}"
        if pid is None:
            hints = patient_hints(row["source_image_path"])
            if len(hints) == 1:
                pid = next(iter(hints))
        if pid is None and dataset_key != "pooled":
            pid = dataset_key
        if pid:
            serial = str(row[serial_col]).strip()
            if re.fullmatch(r"\d+\.0", serial):
                serial = serial[:-2]
            keys.add((pid, serial))
    return keys


def check_separation(pool, tests):
    train_paths = set(pool.source_image_path)
    train_windows = window_keys(pool, "pooled")
    seen_test_paths = set()
    for key, df in tests.items():
        if train_paths & set(df.source_image_path):
            raise ValueError(f"Patient {key}: training/test image paths overlap.")
        overlap = train_windows & window_keys(df, key)
        if overlap:
            raise ValueError(f"Patient {key}: training/test window identifiers overlap: {list(overlap)[:10]}")
        if seen_test_paths & set(df.source_image_path):
            raise ValueError(f"Patient {key}: same images appear in another patient's test set.")
        seen_test_paths.update(df.source_image_path)


def cache_images(df, cache_root):
    out = df.copy()
    if not CACHE_IMAGES_LOCALLY:
        return out
    cached = []
    for source in tqdm(out.source_image_path, desc="Cache images from Drive"):
        source = Path(source)
        tag = hashlib.sha256(str(source).encode()).hexdigest()
        destination = cache_root / f"{tag}{source.suffix.lower()}"
        if not destination.is_file():
            shutil.copy2(source, destination)
        # Decode before any GPU training starts; corrupt images fail early.
        with Image.open(destination) as opened:
            opened.verify()
        cached.append(str(destination))
    out["image_path"] = cached
    return out


